package sart.compiler

import scala.tasty.inspector.{Inspector, Tasty}
import scala.quoted.Quotes
import scala.collection.mutable
import java.nio.file.{Files, Path}
import java.nio.charset.StandardCharsets

/** The Sart Dart emitter.
 *
 *  **Stability**: internal. Integrators should invoke `sart.compiler.Main`
 *  as a CLI (stable contract) rather than instantiating this class
 *  directly. Its constructor signature, member visibility, and internal
 *  `Pass` class are not stable across minor versions.
 *
 *  Internally: one pass over the incoming TASTy that simultaneously
 *  records annotations driving the import header / pubspec / shim
 *  selection, and writes Dart source into a `StringBuilder`.
 *
 *  Any tree shape the emitter doesn't recognise produces a `/* TODO … */`
 *  comment in the output. `sart.compiler.Main --strict` fails the build
 *  when any such comment is emitted.
 */
class DartEmitter(
  outDir: Path,
  sourceRoot: Option[Path] = None,
  projectName: String = "sart_example",
  projectDescription: String = "Scala-authored Flutter app, compiled via Sart."
) extends Inspector:

  // ── State collected across inspection runs ─────────────────────────────
  private val imports       = mutable.LinkedHashSet[String]()
  private val packages      = mutable.LinkedHashSet[DartPkg]()
  private val pubspecBlocks = mutable.LinkedHashSet[String]()
  private val shimsNeeded   = mutable.LinkedHashSet[DartShim]()
  private val bodyBuf       = new StringBuilder

  private case class DartPkg(name: String, version: String, sdk: String)

  /** A Dart-side helper library the emitter ships alongside `main.dart`
   *  so Scala stdlib method calls (e.g. `Option.map`) resolve in Dart.
   *  Each shim is written to `lib/<fileName>` and an `import 'fileName';`
   *  line is added to the emitted imports header.
   */
  private case class DartShim(fileName: String, content: String)

  private val optionShim = DartShim(
    "sart_option.dart",
    """// Generated by Sart — do not edit.
      |// Extension methods mirroring sart.stdlib.Option's Scala vocabulary
      |// on Dart nullable types.
      |
      |extension SartOption<T extends Object> on T? {
      |  // `R` is deliberately unbounded: a lambda may itself return a
      |  // nullable (Scala `Option`-returning) value, which collapses into
      |  // the same `R?` in Dart's nullable lowering.
      |  R? map<R>(R Function(T) f) =>
      |    this == null ? null : f(this as T);
      |
      |  R? flatMap<R>(R? Function(T) f) =>
      |    this == null ? null : f(this as T);
      |
      |  R fold<R>(R ifEmpty, R Function(T) ifPresent) =>
      |    this == null ? ifEmpty : ifPresent(this as T);
      |
      |  void foreach(void Function(T) f) {
      |    if (this != null) f(this as T);
      |  }
      |}
      |""".stripMargin
  )

  private val tryShim = DartShim(
    "sart_try.dart",
    """// Generated by Sart — do not edit.
      |// Scala's Try as a sealed Dart hierarchy. Mirrors the facades in
      |// sart.stdlib.Try / Success / Failure.
      |
      |sealed class Try<T> {
      |  const Try();
      |
      |  Try<R> map<R>(R Function(T) f);
      |  Try<R> flatMap<R>(Try<R> Function(T) f);
      |  R fold<R>(R Function(Object) onFailure, R Function(T) onSuccess);
      |  T getOrElse(T fallback);
      |  bool get isSuccess;
      |  bool get isFailure;
      |  // Sart maps Option<T> to a Dart nullable T?.
      |  T? get toOption;
      |}
      |
      |final class Success<T> extends Try<T> {
      |  final T value;
      |  const Success(this.value);
      |
      |  @override
      |  Try<R> map<R>(R Function(T) f) => Success<R>(f(value));
      |  @override
      |  Try<R> flatMap<R>(Try<R> Function(T) f) => f(value);
      |  @override
      |  R fold<R>(R Function(Object) onFailure, R Function(T) onSuccess) =>
      |      onSuccess(value);
      |  @override
      |  T getOrElse(T fallback) => value;
      |  @override
      |  bool get isSuccess => true;
      |  @override
      |  bool get isFailure => false;
      |  @override
      |  T? get toOption => value;
      |}
      |
      |final class Failure<T> extends Try<T> {
      |  final Object error;
      |  const Failure(this.error);
      |
      |  @override
      |  Try<R> map<R>(R Function(T) f) => Failure<R>(error);
      |  @override
      |  Try<R> flatMap<R>(Try<R> Function(T) f) => Failure<R>(error);
      |  @override
      |  R fold<R>(R Function(Object) onFailure, R Function(T) onSuccess) =>
      |      onFailure(error);
      |  @override
      |  T getOrElse(T fallback) => fallback;
      |  @override
      |  bool get isSuccess => false;
      |  @override
      |  bool get isFailure => true;
      |  @override
      |  T? get toOption => null;
      |}
      |""".stripMargin
  )

  private val eitherShim = DartShim(
    "sart_either.dart",
    """// Generated by Sart — do not edit.
      |// Right-biased Either as a sealed Dart hierarchy. Mirrors the
      |// facades in sart.stdlib.Either / Left / Right.
      |
      |sealed class Either<L, R> {
      |  const Either();
      |
      |  Either<L, R2> map<R2>(R2 Function(R) f);
      |  Either<L, R2> flatMap<R2>(Either<L, R2> Function(R) f);
      |  X fold<X>(X Function(L) onLeft, X Function(R) onRight);
      |  bool get isLeft;
      |  bool get isRight;
      |  // Right value or `fallback` (right-biased).
      |  R getOrElse(R fallback);
      |  // Sart maps Option<R> to a Dart nullable R?.
      |  R? get toOption;
      |  // Flip Left/Right: Right(x).swap == Left(x).
      |  Either<R, L> get swap;
      |}
      |
      |final class Left<L, R> extends Either<L, R> {
      |  final L value;
      |  const Left(this.value);
      |
      |  @override
      |  Either<L, R2> map<R2>(R2 Function(R) f) => Left<L, R2>(value);
      |  @override
      |  Either<L, R2> flatMap<R2>(Either<L, R2> Function(R) f) =>
      |      Left<L, R2>(value);
      |  @override
      |  X fold<X>(X Function(L) onLeft, X Function(R) onRight) =>
      |      onLeft(value);
      |  @override
      |  bool get isLeft => true;
      |  @override
      |  bool get isRight => false;
      |  @override
      |  R getOrElse(R fallback) => fallback;
      |  @override
      |  R? get toOption => null;
      |  @override
      |  Either<R, L> get swap => Right<R, L>(value);
      |}
      |
      |final class Right<L, R> extends Either<L, R> {
      |  final R value;
      |  const Right(this.value);
      |
      |  @override
      |  Either<L, R2> map<R2>(R2 Function(R) f) => Right<L, R2>(f(value));
      |  @override
      |  Either<L, R2> flatMap<R2>(Either<L, R2> Function(R) f) => f(value);
      |  @override
      |  X fold<X>(X Function(L) onLeft, X Function(R) onRight) =>
      |      onRight(value);
      |  @override
      |  bool get isLeft => false;
      |  @override
      |  bool get isRight => true;
      |  @override
      |  R getOrElse(R fallback) => value;
      |  @override
      |  R? get toOption => value;
      |  @override
      |  Either<R, L> get swap => Left<R, L>(value);
      |}
      |""".stripMargin
  )

  // ── Inspector entry point ──────────────────────────────────────────────
  def inspect(using quotes: Quotes)(tastys: List[Tasty[quotes.type]]): Unit =
    val e = new Pass[quotes.type](
      bodyBuf, imports, packages, pubspecBlocks, shimsNeeded,
      optionShim, tryShim, eitherShim, sourceRoot
    )
    for tasty <- tastys do
      e.run(tasty.ast)

  // ── Output ─────────────────────────────────────────────────────────────
  def writeOutput(): Unit =
    val libDir = outDir.resolve("lib")
    Files.createDirectories(libDir)

    // Write every stdlib shim that was flagged as needed during emission.
    // The shim filename goes into the import header so user code resolves
    // against it without any manual setup.
    for shim <- shimsNeeded do
      Files.writeString(libDir.resolve(shim.fileName), shim.content, StandardCharsets.UTF_8)

    // All imports (including shim filenames) flow through the `imports`
    // set — sart.stdlib.Option adds its shim filename in emitTypeRef, and
    // facades like Try/Either add theirs via `@DartImport`. Emitting here
    // without deduplicating would double-import the shim filenames.
    val header = new StringBuilder
    for i <- imports.toList.sorted do
      // Entries are `path` or `path>>>alias` (aliased imports).
      i.split(">>>") match
        case Array(p, a) => header.append(s"import '$p' as $a;\n")
        case _           => header.append(s"import '$i';\n")
    if imports.nonEmpty then header.append('\n')

    val mainDart = header.toString + bodyBuf.toString
    Files.writeString(libDir.resolve("main.dart"), mainDart, StandardCharsets.UTF_8)

    val pubspec = renderPubspec()
    Files.writeString(outDir.resolve("pubspec.yaml"), pubspec, StandardCharsets.UTF_8)

    // Generated-code analysis profile: null-safety shims emit
    // conservative `!` asserts (a shim can't know whether the receiver
    // already promoted), so the two diagnostics those trip are silenced —
    // everything else stays at full strength.
    Files.writeString(outDir.resolve("analysis_options.yaml"),
      """# Generated by Sart — do not edit by hand.
        |analyzer:
        |  errors:
        |    unnecessary_non_null_assertion: ignore
        |    dead_null_aware_expression: ignore
        |    unnecessary_cast: ignore
        |    invalid_use_of_protected_member: ignore
        |""".stripMargin, StandardCharsets.UTF_8)

  /** Lower-bound Dart SDK version the emitter targets. Single source of
   *  truth: drives the pubspec's `environment.sdk` constraint, and the
   *  format step extracts the major.minor from the written pubspec to
   *  pass as `dart format --language-version`. Bump this to roll forward
   *  to a newer Dart language version. */
  private val sdkFloor = "3.12.0"

  private def renderPubspec(): String =
    val b = new StringBuilder
    b.append("# Generated by Sart — do not edit by hand.\n")
    b.append(s"name: $projectName\n")
    b.append(s"description: $projectDescription\n")
    b.append("publish_to: 'none'\n")
    b.append("version: 0.1.0\n\n")
    b.append("environment:\n")
    b.append(s"  sdk: '>=$sdkFloor <4.0.0'\n\n")
    b.append("dependencies:\n")
    for p <- packages.toList.sortBy(_.name) do
      if p.sdk.nonEmpty then
        b.append(s"  ${p.name}:\n")
        b.append(s"    sdk: ${p.sdk}\n")
      else if p.version.nonEmpty then
        b.append(s"  ${p.name}: ${p.version}\n")
      else
        b.append(s"  ${p.name}: any\n")
    // Multiple annotations may each contribute a `flutter:` section
    // (uses-material-design from the Widget facade, assets from the app).
    // YAML forbids duplicate mapping keys, so those sections merge into
    // one — their child lines concatenated under a single `flutter:`.
    val normalized = pubspecBlocks.toList.map(normalizePubspecBlock).filter(_.nonEmpty)
    val (flutterBlocks, otherBlocks) =
      normalized.partition(_.linesIterator.nextOption().exists(_.trim == "flutter:"))
    for block <- otherBlocks do
      b.append('\n')
      b.append(block)
      if !block.endsWith("\n") then b.append('\n')
    if flutterBlocks.nonEmpty then
      b.append("\nflutter:\n")
      for block <- flutterBlocks do
        for line <- block.linesIterator.drop(1) do
          b.append(line)
          b.append('\n')
    b.toString

  /** Produce a canonical indentation for a `@DartPubspec` block so a
   *  sloppily-written annotation (`"""` with surrounding blank lines or
   *  leading whitespace matching the source indentation) still lands in
   *  the pubspec as valid YAML.
   *
   *  Steps: drop leading/trailing blank lines, find the minimum indent of
   *  non-blank lines, strip that indent from every line.
   */
  private def normalizePubspecBlock(raw: String): String =
    val lines = raw.split('\n').toList
      .dropWhile(_.trim.isEmpty)
      .reverse.dropWhile(_.trim.isEmpty).reverse
    if lines.isEmpty then ""
    else
      val minIndent = lines
        .filter(_.trim.nonEmpty)
        .map(_.takeWhile(_ == ' ').length)
        .minOption
        .getOrElse(0)
      lines.map(l => if l.length >= minIndent then l.drop(minIndent) else l)
        .mkString("\n")

  // ── Per-run emitter, parameterized over Quotes ─────────────────────────
  //
  // Keeping everything inside a nested class means the reflect types stay
  // path-dependent on a stable `quotes` — we don't have to thread it through
  // every method signature by hand.
  private class Pass[Q <: Quotes & Singleton](
    out: StringBuilder,
    imports: mutable.LinkedHashSet[String],
    packages: mutable.LinkedHashSet[DartPkg],
    pubspecBlocks: mutable.LinkedHashSet[String],
    shimsNeeded: mutable.LinkedHashSet[DartShim],
    optionShim: DartShim,
    tryShim: DartShim,
    eitherShim: DartShim,
    sourceRoot: Option[Path]
  )(using val q: Q):
    import q.reflect.*

    private var indent = 0
    private def ind(): String = "  " * indent
    private def line(s: String): Unit = { out.append(ind()); out.append(s); out.append('\n') }
    private def blank(): Unit = out.append('\n')

    // ── Annotation helpers ───────────────────────────────────────────────

    private def annoFqn(a: Term): String = a.tpe.typeSymbol.fullName

    private def hasNative(sym: Symbol): Boolean =
      sym.annotations.exists(a => annoFqn(a) == "sart.dart.native")

    private def hasJsonModel(sym: Symbol): Boolean =
      sym.annotations.exists(a => annoFqn(a) == "sart.dart.JsonModel")

    /** The JSON `type` discriminator for a sealed-hierarchy member:
     *  `@JsonTag("...")` if present, else the class's simple name.
     */
    private def jsonTagOf(sym: Symbol): String =
      sym.annotations.collectFirst {
        case a if annoFqn(a) == "sart.dart.JsonTag" =>
          constArgs(a).collectFirst { case s: String => s }
      }.flatten.getOrElse(sym.name)

    /** Unwrap a `Literal(Constant(...))` into its underlying value, whatever
     *  the concrete `Constant` subtype is.
     */
    private def litValue(t: Term): Option[Any] = t match
      case Literal(c) => Some(c.value)
      case _ => None

    /** Extract constant args (Strings/Ints/Booleans) from an annotation tree. */
    private def constArgs(a: Term): List[Any] =
      a match
        case Apply(_, args) =>
          args.flatMap {
            case t if litValue(t).isDefined => litValue(t).toList
            case NamedArg(_, t) if litValue(t).isDefined => litValue(t).toList
            case _ => Nil
          }
        case _ => Nil

    /** Named-arg lookup on an annotation (falls back to positional). */
    private def annoArg(a: Term, name: String, positional: Int): Option[Any] =
      a match
        case Apply(_, args) =>
          val named = args.collectFirst {
            case NamedArg(n, t) if n == name && litValue(t).isDefined => litValue(t).get
          }
          named.orElse {
            args.zipWithIndex.collectFirst {
              case (t, i) if i == positional && litValue(t).isDefined => litValue(t).get
            }
          }
        case _ => None

    private def recordAnnotations(sym: Symbol): Unit =
      for a <- sym.annotations do
        annoFqn(a) match
          case "sart.dart.DartImport" =>
            constArgs(a).collectFirst { case s: String => s }.foreach { path =>
              val alias = importAlias(sym)
              imports += alias.map(al => s"$path>>>$al").getOrElse(path)
              // If the @DartImport names a stdlib shim, register the shim
              // file for emission. The shim's own filename already lands
              // in `imports` so there's no double-import.
              path match
                case "sart_try.dart"    => shimsNeeded += tryShim
                case "sart_either.dart" => shimsNeeded += eitherShim
                case "sart_option.dart" => shimsNeeded += optionShim
                case _                  => ()
            }
          case "sart.dart.DartPackage" =>
            val name    = annoArg(a, "name",    0).collect { case s: String => s }.getOrElse("")
            val version = annoArg(a, "version", 1).collect { case s: String => s }.getOrElse("")
            val sdk     = annoArg(a, "sdk",     2).collect { case s: String => s }.getOrElse("")
            if name.nonEmpty then packages += DartPkg(name, version, sdk)
          case "sart.dart.DartPubspec" =>
            constArgs(a).collectFirst { case s: String => s }.foreach(pubspecBlocks += _)
          case _ =>

    /** Pull the emitted Dart name from `@DartName(...)` if present, and
     *  prefix with the facade's import alias when its `@DartImport`
     *  declares one.
     */
    private def dartName(sym: Symbol): String =
      val base = sym.annotations.collectFirst {
        case a if annoFqn(a) == "sart.dart.DartName" =>
          constArgs(a).collectFirst { case s: String => s }
      }.flatten.getOrElse(sym.name)
      importAlias(sym).map(al => s"$al.$base").getOrElse(base)

    /** The import alias declared via a facade's `@DartAlias`, if any. */
    private def importAlias(sym: Symbol): Option[String] =
      sym.annotations.collectFirst {
        case a if annoFqn(a) == "sart.dart.DartAlias" =>
          constArgs(a).collectFirst { case s: String if s.nonEmpty => s }
      }.flatten

    // Dart reserved words that user-chosen Scala identifiers sometimes
    // collide with. We don't need the full keyword list — just the ones
    // that actually break code when used as identifiers.
    private val dartReserved = Set(
      "default", "class", "const", "enum", "extends", "false", "final",
      "null", "return", "super", "switch", "this", "true", "var",
      "void", "while", "with", "try", "throw", "is", "as", "in", "of",
      "new", "if", "else", "for", "do"
    )

    /** Rewrite Dart-keyword collisions for identifiers used in the emitted
     *  source (parameters, locals, field names). Adds a trailing underscore
     *  so the identifier is unambiguously Dart-valid while staying readable.
     */
    private def dartSafeName(name: String): String =
      if dartReserved(name) then s"${name}_" else name

    // ── Top-level driver ─────────────────────────────────────────────────

    def run(tree: Tree): Unit =
      // Pre-register companion modules of user-emitted classes before
      // walking, so merge decisions don't depend on declaration order.
      registerCompanions(tree)
      tree match
        case p: PackageClause => p.stats.foreach(runTop)
        case other            => runTop(other)

    // Companion modules whose members fold into their class's emission as
    // Dart statics (a same-named separate class would be a collision).
    private val companionModules = mutable.Map[Symbol, ClassDef]()

    private def registerCompanions(t: Tree): Unit = t match
      case p: PackageClause => p.stats.foreach(registerCompanions)
      case cd: ClassDef if cd.symbol.name.endsWith("$") && !hasNative(cd.symbol) =>
        val companion = cd.symbol.companionClass
        if companion.exists && !hasNative(companion) && !companion.flags.is(Flags.Enum)
           && !companion.name.contains("$") then
          companionModules(companion) = cd
      case _ => ()

    private def runTop(t: Tree): Unit = t match
      case _: Import =>
        () // Scala imports are irrelevant; we emit our own Dart imports
      case p: PackageClause =>
        p.stats.foreach(runTop)
      case cd: ClassDef =>
        val sym = cd.symbol
        val name = sym.name
        if hasNative(sym) then
          recordAnnotations(sym)
        else if name.endsWith("$package$") || name.endsWith("$package") then
          // Scala 3 stores top-level defs inside a synthetic package class;
          // descend and treat its stats as top-level trees.
          cd.body.foreach(runTop)
        else if isMainWrapper(cd) then
          () // `@main def foo` generates a wrapper class we don't want to emit.
        else if sym.flags.is(Flags.Enum) && !sym.flags.is(Flags.Case) then
          // The enum parent class (`enum Filter { case All, … }` produces
          // a sealed `class Filter extends scala.reflect.Enum`). Skip —
          // we emit the Dart enum from the companion object below instead.
          ()
        else if name.endsWith("$") then
          // A module class. Interesting varieties:
          //   - @native facade object              → record annotations, skip
          //   - enum companion                     → emit the Dart enum
          //   - `case object Foo` module           → emit `class Foo {}`
          //   - given-value module with impl body  → emit as concrete class
          //   - plain case-class / other companion → skip
          val companion = sym.companionClass
          val moduleVal = sym.companionModule
          if hasNative(sym) || (moduleVal.exists && hasNative(moduleVal))
             || (companion.exists && hasNative(companion)) then
            recordAnnotations(sym)
            if moduleVal.exists then recordAnnotations(moduleVal)
            if companion.exists then recordAnnotations(companion)
          else if companion.exists && companion.flags.is(Flags.Enum) then
            emitEnumFromCompanion(cd, companion)
          else if companion.exists && companionModules.contains(companion) then
            () // Statics merged into the companion class's own emission.
          else if sym.flags.is(Flags.Case) then
            emitCaseObject(cd)
          else if hasUserDefinedBody(cd) || hasUserFields(cd) then
            // A `$`-class with user-written members. Two varieties:
            //   - `given X: T with { … }` singleton → concrete class, so the
            //     corresponding top-level `val X = X$()` resolves.
            //   - a plain user `object` → a Dart class of static members.
            if moduleVal.exists && moduleVal.flags.is(Flags.Given) then emitClassDef(cd)
            else emitStaticObject(cd)
          // Plain companions (case-class `$`, etc.) — skip.
        else if name.contains("$") || sym.flags.is(Flags.Synthetic) then
          () // Synthetic/anonymous classes — skip.
        else
          emitClassDef(cd)
      case dd: DefDef =>
        if dd.symbol.flags.is(Flags.ExtensionMethod) then
          // @native extension defs are facades for REAL Dart extensions
          // (go_router's `context.go`) — record imports, emit nothing;
          // call sites emit `receiver.method(args)` and resolve against
          // the actual Dart extension.
          if hasNative(dd.symbol) then recordAnnotations(dd.symbol)
          else emitExtensionMethod(dd)
        else emitTopLevelDef(dd)
      case vd: ValDef =>
        // The value side of a facade `object` (`val Uri = Uri$()`) has no
        // Dart existence — record its annotations and move on.
        val tpeSym = vd.tpt.tpe.typeSymbol
        val nativeModule = hasNative(vd.symbol) || (tpeSym.exists && (hasNative(tpeSym) || {
          val c = tpeSym.companionClass
          c.exists && hasNative(c)
        }))
        if nativeModule then recordAnnotations(vd.symbol)
        else emitTopLevelVal(vd)
      case _ =>
        line(s"/* TODO top-level: ${t.getClass.getSimpleName} */")

    /** Emit a Dart class for a Scala `case object`. The module class has
     *  the form `FooName$` in TASTy; we strip the trailing `$` for the
     *  Dart name. For now the emission is an empty class (no singleton
     *  value-level support); references to the object as a value will
     *  need follow-up work to translate as `FooName()` or a const instance.
     */
    private def emitCaseObject(cd: ClassDef): Unit =
      val objName = cd.symbol.name.stripSuffix("$")
      val parentTpt = realParent(cd)
      val ext = parentTpt.map(t => s" extends ${emitTypeRef(t.tpe)}").getOrElse("")
      emitSourceAttribution(cd.symbol)
      line(s"class $objName$ext {}")
      blank()

    /** Emit a Dart enum from the companion module of a Scala 3 enum class.
     *
     *  Simple enum cases (no parameters) are stored as `val` members of the
     *  companion, each typed as the enum class itself. For these we emit
     *  `enum Name { A, B, C }`.
     *
     *  Parameterised cases (e.g. `case Foo(x: Int)`) appear as their own
     *  subclass `ClassDef`s elsewhere in the tree; this helper leaves a
     *  TODO marker for that path — sealed-hierarchy emission (task 15)
     *  will handle it.
     */
    private def emitEnumFromCompanion(companionCd: ClassDef, enumCls: Symbol): Unit =
      val caseVals = companionCd.body.collect {
        case vd: ValDef
            if !vd.symbol.flags.is(Flags.Synthetic)
            && vd.tpt.tpe.typeSymbol == enumCls =>
          vd
      }
      if caseVals.nonEmpty then
        val names = caseVals.map(_.name).mkString(", ")
        emitSourceAttribution(enumCls)
        line(s"enum ${enumCls.name} { $names }")
        blank()
      else
        line(s"/* TODO: parameterised enum ${enumCls.name} — cases are subclasses */")
        blank()

    /** Emit a `/// Source: <path>:<line>` dartdoc comment for the given
     *  symbol's source position. No-op when the symbol has no tracked
     *  position (e.g. synthetic classes we do still emit).
     *
     *  Path relativisation: if a `sourceRoot` was passed to the emitter
     *  (typically the sbt base directory) and the source file lives under
     *  it, we emit `<rel-path>:<line>`. Otherwise the absolute path goes
     *  through — verbose but never misleading.
     */
    private def emitSourceAttribution(sym: Symbol): Unit =
      val pos = sym.pos
      if pos.isEmpty then return
      // The compiler stores source-file paths relative to whatever dir
      // it was invoked from. Resolve a relative path against sourceRoot
      // (the sbt baseDirectory), not the JVM cwd which happens to be
      // the compiler module's dir.
      val raw = pos.get.sourceFile.getJPath
      val sourcePath = raw.map { p =>
        if p.isAbsolute then p
        else sourceRoot.getOrElse(java.nio.file.Paths.get(".").toAbsolutePath).resolve(p).normalize
      }
      sourcePath.foreach { sp =>
        val displayed = sourceRoot match
          case Some(root) if sp.startsWith(root) => root.relativize(sp).toString
          case _                                 => sp.toString
        line(s"/// Source: $displayed:${pos.get.startLine + 1}")
      }

    /** Does this class body carry a user-written (non-synthetic,
     *  non-`<init>`) method? We use this to distinguish `given X: T with
     *  { … }` modules (which have user methods to carry into Dart) from
     *  plain case-class/object companions (which only have synthetic
     *  `apply`/`unapply`/etc.).
     */
    private def hasUserDefinedBody(cd: ClassDef): Boolean =
      cd.body.exists {
        case dd: DefDef =>
          !dd.symbol.flags.is(Flags.Synthetic) && dd.symbol.name != "<init>"
        case _ => false
      }

    private def hasUserFields(cd: ClassDef): Boolean =
      cd.body.exists {
        case vd: ValDef => !vd.symbol.flags.is(Flags.Synthetic)
        case _          => false
      }

    /** A user `object` → a Dart class of static members with a private
     *  constructor. `Session.user` / `Service.restful(...)` call sites
     *  line up because the Scala module reference prints as the bare
     *  object name.
     */
    private def staticObjectMembers(cd: ClassDef): List[Definition] =
      cd.body.collect {
        case vd: ValDef => vd
        case dd: DefDef => dd
      }.filterNot { stat =>
        stat.symbol.flags.is(Flags.Synthetic) ||
        stat.symbol.flags.is(Flags.ParamAccessor) ||
        stat.symbol.flags.is(Flags.FieldAccessor) ||
        stat.symbol.name.contains("$default$") ||
        stat.symbol.name.endsWith("_=") ||
        stat.symbol.name == "<init>"
      }

    private def emitStaticObject(cd: ClassDef): Unit =
      val sym = cd.symbol
      val objName = sym.name.stripSuffix("$")
      val memberStats = staticObjectMembers(cd)
      emitSourceAttribution(sym)
      line(s"class $objName {")
      indent += 1
      line(s"$objName._();")
      blank()
      for stat <- memberStats do
        stat match
          case vd: ValDef => emitField(vd, static = true)
          case dd: DefDef => emitMethod(dd, static = true)
      indent -= 1
      line("}")
      blank()

    /** Recognise the `@main def foo` wrapper class Scala 3 synthesises.
     *  Heuristic: the class contains a `main(args: Array[String])` method.
     *  The synthesised main may or may not be flagged `Synthetic` across
     *  Scala 3 minor versions, so we check the method signature directly.
     */
    private def isMainWrapper(cd: ClassDef): Boolean =
      cd.body.exists {
        case dd: DefDef if dd.symbol.name == "main" =>
          val ps = dd.paramss.flatMap(_.params).collect { case vd: ValDef => vd }
          ps match
            case List(vd) => vd.tpt.tpe.typeSymbol.fullName == "scala.Array"
            case _        => false
        case _ => false
      }

    // ── Classes ──────────────────────────────────────────────────────────

    // Scala auto-parents (roots, case-class/serializable markers) we never
    // carry into Dart. Matching both fully-qualified and simple names
    // because `Serializable` can resolve as `scala.` or `java.io.` depending
    // on alias path.
    private val skippedParentFqns = Set(
      "java.lang.Object", "scala.Any", "sart.dart.DartObject",
      "scala.Product", "scala.Serializable", "scala.Equals",
      "java.io.Serializable"
    )
    private val skippedParentSimples = Set("Product", "Serializable", "Equals")

    /** Walk tree shapes like `Apply(TypeApply(Select(New(tt), "<init>"),
     *  tpArgs), valArgs)` to the underlying parent `TypeTree`.
     */
    private def findParentType(t: Tree): Option[TypeTree] = t match
      case tt: TypeTree        => Some(tt)
      case New(tt: TypeTree)   => Some(tt)
      case Apply(inner, _)     => findParentType(inner)
      case TypeApply(inner, _) => findParentType(inner)
      case Select(inner, _)    => findParentType(inner)
      case _                   => None

    /** First "real" parent type from a ClassDef's parent list (i.e. dropping
     *  scala.Any / Object / DartObject / case-class markers).
     */
    private def realParent(cd: ClassDef): Option[TypeTree] =
      cd.parents.flatMap(findParentType).find { tt =>
        val s = tt.tpe.typeSymbol
        !skippedParentFqns(s.fullName) && !skippedParentSimples(s.name)
      }

    /** Full parent decomposition: the extends-parent with its constructor
     *  arguments, plus every further real parent for the `with` clause.
     */
    private case class ParentInfo(
      extendsTpt: Option[TypeTree],
      superArgs: List[Term],
      withTpts: List[TypeTree]
    )

    private def parentCtorArgs(t: Tree): List[Term] = t match
      case Apply(inner, args) => parentCtorArgs(inner) ++ args
      case TypeApply(inner, _) => parentCtorArgs(inner)
      case _                   => Nil

    private def parentInfo(cd: ClassDef): ParentInfo =
      val real = cd.parents.flatMap { p =>
        findParentType(p).filter { tt =>
          val s = tt.tpe.typeSymbol
          !skippedParentFqns(s.fullName) && !skippedParentSimples(s.name)
        }.map(tt => (tt, parentCtorArgs(p)))
      }
      real match
        case Nil                 => ParentInfo(None, Nil, Nil)
        case (tt, args) :: rest  => ParentInfo(Some(tt), args, rest.map(_._1))

    private def emitClassDef(cd: ClassDef): Unit =
      val sym = cd.symbol
      if hasNative(sym) then
        recordAnnotations(sym)
        return

      // `runTop` already filters by name (skips $-ending companions unless
      // they're enum, case-object, or have a user-defined body) and
      // synthetic classes, so here we only guard against stray inner
      // synthesised helpers that somehow reached emitClassDef.
      val rawName = sym.name
      if sym.flags.is(Flags.Synthetic) then return
      val className = rawName

      val parents = parentInfo(cd)
      val withClause =
        if parents.withTpts.isEmpty then ""
        else parents.withTpts.map(tt => emitTypeRef(tt.tpe)).mkString(" with ", ", ", "")
      val extendsClause =
        parents.extendsTpt.map(tt => s" extends ${emitTypeRef(tt.tpe)}").getOrElse("") + withClause

      // Primary-constructor parameters become `final` fields in Dart, plus
      // a named constructor of the form `ClassName({required this.field});`.
      val ctor = cd.constructor
      val ctorParams: List[ValDef] = ctor.paramss.flatMap(_.params).collect { case vd: ValDef => vd }
      val typeParams: String = typeParamSig(ctor)

      // Member stats (val/var/def/override def); the primary-ctor body is
      // in `cd.body`, separate from the constructor params.
      val memberStats = cd.body.collect {
        case vd: ValDef => vd
        case dd: DefDef => dd
      }.filterNot { stat =>
        // Drop compiler-synthesised accessors for ctor params (we emit the
        // fields ourselves), var setters (`x_=`), and default-value getters
        // (their literals are folded into the emitted parameter shape).
        stat.symbol.flags.is(Flags.ParamAccessor) ||
        stat.symbol.flags.is(Flags.Synthetic) ||
        stat.symbol.flags.is(Flags.FieldAccessor) ||
        stat.symbol.name.endsWith("_=") ||
        stat.symbol.name.contains("$default$") ||
        stat.symbol.name == "<init>"
      }

      // Sealed parents (`sealed trait Shape`) legitimately have empty
      // bodies, so we no longer short-circuit on emptiness here — the
      // `@main` wrapper we used to catch via this rule is now caught by
      // `isMainWrapper` upstream. Scala traits and abstract classes both
      // map to Dart `abstract class` — Dart has no trait-specific keyword.
      // Parameterless, parentless, non-sealed traits become `mixin class`
      // — usable both in extends position and in a `with` clause (Dart 3).
      // A parameterless trait WITH a parent is a Dart `mixin … on Parent`
      // — the exact translation of `mixin Screen on StatelessWidget`,
      // usable only in `with` clauses (as in the original Dart).
      val isMixinOn = sym.flags.is(Flags.Trait) && ctorParams.isEmpty
        && !sym.flags.is(Flags.Sealed) && parents.extendsTpt.nonEmpty
      val keyword =
        if sym.flags.is(Flags.Sealed) then "sealed class"
        else if isMixinOn then "mixin"
        else if sym.flags.is(Flags.Trait) && ctorParams.isEmpty
                && parents.extendsTpt.isEmpty && parents.withTpts.isEmpty then "mixin class"
        else if sym.flags.is(Flags.Trait) || sym.flags.is(Flags.Abstract) then "abstract class"
        else "class"
      val parentClause =
        if isMixinOn then
          val onTypes = (parents.extendsTpt.toList ++ parents.withTpts)
            .map(tt => emitTypeRef(tt.tpe)).mkString(", ")
          s" on $onTypes"
        else extendsClause

      emitSourceAttribution(sym)
      line(s"$keyword $className$typeParams$parentClause {")
      indent += 1

      // `val` ctor params become fields. Plain params also get a
      // private-local ParamAccessor from dotty, so those only become
      // fields when a member body actually references them — otherwise
      // they stay constructor-local (typically just feeding `super(...)`).
      val publicAccessors = cd.body.collect {
        case vd: ValDef if vd.symbol.flags.is(Flags.ParamAccessor)
          && !vd.symbol.flags.is(Flags.PrivateLocal) => vd.name
      }.toSet
      def usedInMembers(name: String): Boolean =
        val acc = new TreeAccumulator[Boolean]:
          def foldTree(found: Boolean, tree: Tree)(owner: Symbol): Boolean =
            found || (tree match
              case id: Ident   => id.name == name
              case s: Select   => s.name == name || foldOverTree(false, s)(owner)
              case _           => foldOverTree(false, tree)(owner))
        memberStats.exists(stat => acc.foldTree(false, stat)(sym))
      // A ctor param named `key` typed Key on a Widget subclass forwards
      // to the framework's own field (`{super.key}`) — declaring a
      // shadowing field would leave Widget.key null and silently break
      // GlobalKey addressing.
      def isSuperKeyParam(p: ValDef): Boolean =
        // Only meaningful when the parent chain actually reaches the
        // framework's Widget (a plain data class named `key` must keep
        // its own field — there is no `super.key` to forward to).
        p.name == "key" && emitTypeRef(p.tpt.tpe) == "Key" && !sym.flags.is(Flags.Case) &&
          parents.extendsTpt.exists { t =>
            val p = t.tpe.typeSymbol
            p.exists && p.fullName != "java.lang.Object" && p.fullName != "scala.AnyRef"
          }
      def isFieldParam(p: ValDef): Boolean =
        !isSuperKeyParam(p) &&
          (sym.flags.is(Flags.Case) || publicAccessors.contains(p.name) || usedInMembers(p.name))
      // A ctor param defaulted to `null` needs a nullable field type —
      // `final Key key;` with `{this.key = null}` is an invalid_assignment.
      val nullDefaultedParams: Set[String] =
        dartParamShape(ctor.symbol, ctorParams).named
          .collect { case (p, "null") => p.name }.toSet
      for p <- ctorParams if isFieldParam(p) do
        val t  = emitTypeRef(p.tpt.tpe)
        val tn = if nullDefaultedParams.contains(p.name) && !t.endsWith("?") && t != "dynamic" then s"$t?" else t
        // A `var` ctor param: the mutability lives on the ACCESSOR field,
        // not the parameter symbol.
        val accessor = sym.fieldMember(p.name)
        val isVar = (accessor.exists && accessor.flags.is(Flags.Mutable)) || p.symbol.flags.is(Flags.Mutable)
        val fin = if isVar then "" else "final "
        line(s"$fin$tn ${p.name};")

      // User-class primary constructors: params without defaults stay
      // positional (matching how Scala call sites invoke them); params
      // with literal defaults become a Dart named section carrying the
      // default (`{this.x = 1}`), so Scala call sites that omit them keep
      // working. Parent constructor arguments become a `: super(...)`
      // initializer. Facade classes are different — no Dart ctor is ever
      // emitted for them; the real Dart class defines the shape.
      val ctorShape = dartParamShape(ctor.symbol, ctorParams)
      val superInit =
        if parents.superArgs.isEmpty then ""
        else
          val parentSym = parents.extendsTpt.map(_.tpe.typeSymbol).getOrElse(Symbol.noSymbol)
          val rendered =
            if parentSym.exists && !hasNative(parentSym) then
              emitUserCallArgs(parentSym.primaryConstructor, parents.superArgs)
            else emitArgs(parents.superArgs)
          s" : super($rendered)"
      if ctorParams.nonEmpty || superInit.nonEmpty then
        def ctorParamDecl(p: ValDef): String =
          if isSuperKeyParam(p) then "super.key"
          else if isFieldParam(p) then s"this.${p.name}"
          else s"${emitTypeRef(p.tpt.tpe)} ${p.name}"
        val pos = ctorShape.positional.map(ctorParamDecl)
        val nmd = ctorShape.named.map((p, d) =>
          if isSuperKeyParam(p) then "super.key" else s"${ctorParamDecl(p)} = $d")
        val paramList =
          if nmd.isEmpty then pos.mkString(", ")
          else if pos.isEmpty then nmd.mkString("{", ", ", "}")
          else pos.mkString(", ") + ", " + nmd.mkString("{", ", ", "}")
        line(s"$className($paramList)$superInit;")
        blank()

      for stat <- memberStats do
        stat match
          case vd: ValDef => emitField(vd)
          case dd: DefDef => emitMethod(dd)

      if sym.flags.is(Flags.Case) && ctorParams.nonEmpty then
        emitCaseClassSynths(className, ctorParams, ctorShape)

      // JSON codec synthesis: annotated case classes (or every member of
      // an annotated sealed hierarchy) get fromJson/toJson; the sealed
      // parent itself gets the type-tag dispatch factory.
      val sealedJsonParent = parents.extendsTpt.map(_.tpe.typeSymbol)
        .filter(p => p.flags.is(Flags.Sealed) && hasJsonModel(p))
      if sym.flags.is(Flags.Case)
         && (hasJsonModel(sym) || sealedJsonParent.isDefined) then
        emitJsonSynths(className, ctorShape, sealedJsonParent.map(_ => jsonTagOf(sym)))
      if sym.flags.is(Flags.Sealed) && hasJsonModel(sym) then
        emitSealedJsonDispatch(className, sym)

      // Companion-object members land here as Dart statics.
      companionModules.get(sym).foreach { moduleCd =>
        val statics = staticObjectMembers(moduleCd)
        if statics.nonEmpty then blank()
        for stat <- statics do
          stat match
            case vd: ValDef => emitField(vd, static = true)
            case dd: DefDef => emitMethod(dd, static = true)
      }

      indent -= 1
      line("}")
      blank()

    /** Emit the Dart equivalents of a Scala case class's auto-generated
     *  members: `==`, `hashCode`, `toString`, `copyWith`. Scala's synthesised
     *  versions (`equals`, `canEqual`, etc.) are `Synthetic` so they're
     *  filtered out above and we write our own instead.
     *
     *  Nullability caveat: `copyWith({T? field})` with `field ?? this.field`
     *  can't distinguish "not provided" from "provided null" for nullable
     *  fields. Good enough while case-class fields are non-nullable; when
     *  `Option[T]` → `T?` lands (Phase 2), swap in a sentinel.
     */
    private def emitCaseClassSynths(className: String, params: List[ValDef], shape: DartParamShape): Unit =
      val names = params.map(_.name)
      val types = params.map(p => emitTypeRef(p.tpt.tpe))

      // ==  (the constructor above already emitted a trailing blank line).
      line("@override")
      line("bool operator ==(Object other) =>")
      indent += 1
      val eqCheck = names.map(n => s"other.$n == $n").mkString(" && ")
      line(s"identical(this, other) ||")
      line(s"other is $className && $eqCheck;")
      indent -= 1
      blank()

      // hashCode — `Object.hash` takes at most 20 positional values; wide
      // records switch to `Object.hashAll`.
      line("@override")
      if names.size == 1 then
        line(s"int get hashCode => ${names.head}.hashCode;")
      else if names.size <= 20 then
        line(s"int get hashCode => Object.hash(${names.mkString(", ")});")
      else
        line(s"int get hashCode => Object.hashAll([${names.mkString(", ")}]);")
      blank()

      // toString — each `$$name` in Scala source becomes `$name` in the
      // emitted Dart, which Dart then interpolates at runtime.
      line("@override")
      val tsParts = names.map(n => s"$n: $$$n").mkString(", ")
      line(s"String toString() => '$className($tsParts)';")
      blank()

      // copyWith — method's own parameters are named (Dart convention for
      // `copyWith`); the body's constructor call mirrors the emitted ctor
      // shape (positional prefix, named section for defaulted params).
      // Already-nullable field types (Option-mapped, dynamic) keep as-is.
      val cwParams = names.zip(types).map { case (n, t) =>
        val opt = if t.endsWith("?") || t == "dynamic" then t else s"$t?"
        s"$opt $n"
      }.mkString(", ")
      val cwArgs =
        (shape.positional.map(p => s"${p.name} ?? this.${p.name}") ++
          shape.named.map((p, _) => s"${p.name}: ${p.name} ?? this.${p.name}")).mkString(", ")
      line(s"$className copyWith({$cwParams}) =>")
      indent += 1
      line(s"$className($cwArgs);")
      indent -= 1

    // ── JSON codec synthesis (@JsonModel) ────────────────────────────────

    /** Decode `src` (a `dynamic` from a JSON map) into the Dart value for
     *  Scala type `tpe`.
     */
    private def jsonDecodeExpr(rawTpe: TypeRepr, src: String): String =
      val tpe = rawTpe.dealias
      val sym = tpe.typeSymbol
      def arg0: Option[TypeRepr] = tpe match
        case AppliedType(_, List(a: TypeRepr)) => Some(a)
        case _                                 => None
      def arg1: Option[TypeRepr] = tpe match
        case AppliedType(_, List(_, b: TypeRepr)) => Some(b)
        case _                                    => None
      sym.fullName match
        case "scala.Int"        => s"($src as num).toInt()"
        case "scala.Long"       => s"($src as num).toInt()"
        case "scala.Double"     => s"($src as num).toDouble()"
        case "scala.Boolean"    => s"($src as bool)"
        case "java.lang.String" => s"($src as String)"
        case "sart.dart.Dyn"    => src
        case "scala.Option" | "sart.stdlib.Option" =>
          arg0.map(a => s"$src == null ? null : ${jsonDecodeExpr(a, src)}")
            .getOrElse(src)
        case "scala.collection.immutable.List" | "scala.collection.Seq"
           | "scala.collection.immutable.Seq" =>
          arg0.map(a => s"($src as List<dynamic>).map((e) => ${jsonDecodeExpr(a, "e")}).toList()")
            .getOrElse(src)
        case "scala.collection.immutable.Map" =>
          arg1 match
            // Dyn-valued maps stay raw; every other value type decodes
            // element-wise through this same dispatcher.
            case Some(vt) if vt.dealias.typeSymbol.fullName == "sart.dart.Dyn" =>
              s"($src as Map<String, dynamic>)"
            case Some(vt) =>
              s"($src as Map<String, dynamic>).map((k, v) => MapEntry(k, ${jsonDecodeExpr(vt, "v")}))"
            case _ => s"($src as Map<String, dynamic>)"
        case _ if sym.flags.is(Flags.Case) || (sym.flags.is(Flags.Sealed) && hasJsonModel(sym)) =>
          s"${sym.name}.fromJson($src as Map<String, dynamic>)"
        case _ => src

    /** Encode the field value `ref` of Scala type `tpe` for a JSON map. */
    private def jsonEncodeExpr(rawTpe: TypeRepr, ref: String): String =
      val tpe = rawTpe.dealias
      val sym = tpe.typeSymbol
      def arg0: Option[TypeRepr] = tpe match
        case AppliedType(_, List(a: TypeRepr)) => Some(a)
        case _                                 => None
      sym.fullName match
        case "scala.Int" | "scala.Long" | "scala.Double" | "scala.Boolean"
           | "java.lang.String" | "sart.dart.Dyn" => ref
        case "scala.Option" | "sart.stdlib.Option" =>
          arg0 match
            case Some(a) if isJsonObjectLike(a) => s"$ref?.toJson()"
            case _                              => ref
        case "scala.collection.immutable.List" | "scala.collection.Seq"
           | "scala.collection.immutable.Seq" =>
          arg0 match
            case Some(a) if isJsonObjectLike(a) => s"$ref.map((e) => e.toJson()).toList()"
            case _                              => ref
        case "scala.collection.immutable.Map" =>
          tpe match
            case AppliedType(_, List(_, v: TypeRepr)) if isJsonObjectLike(v) =>
              s"$ref.map((k, v) => MapEntry(k, v.toJson()))"
            case _ => ref
        case _ if isJsonObjectLike(tpe) => s"$ref.toJson()"
        case _ => ref

    private def isJsonObjectLike(tpe: TypeRepr): Boolean =
      val sym = tpe.dealias.typeSymbol
      (sym.flags.is(Flags.Case) && !hasNative(sym)) ||
        (sym.flags.is(Flags.Sealed) && hasJsonModel(sym))

    /** `fromJson` / `toJson` for a @JsonModel case class, wire-compatible
     *  with json_serializable output (`explicitToJson: true` shape). A
     *  sealed-hierarchy member also writes its `type` tag.
     */
    /** The JSON key for a @JsonModel field: `@JsonField("...")` if
     *  present, else the field's own name.
     */
    private def jsonKeyOf(p: ValDef): String =
      p.symbol.annotations.collectFirst {
        case a if annoFqn(a) == "sart.dart.JsonField" =>
          constArgs(a).collectFirst { case s: String => s }
      }.flatten.getOrElse(p.name)

    private def emitJsonSynths(className: String, shape: DartParamShape, tag: Option[String]): Unit =
      val all = shape.positional ++ shape.named.map(_._1)
      // fromJson — constructor call mirrors the emitted ctor shape.
      val ctorArgs =
        (shape.positional.map(p => jsonDecodeExpr(p.tpt.tpe, s"json['${jsonKeyOf(p)}']")) ++
          shape.named.map((p, _) => s"${p.name}: ${jsonDecodeExpr(p.tpt.tpe, s"json['${jsonKeyOf(p)}']")}"))
          .mkString(", ")
      line(s"static $className fromJson(Map<String, dynamic> json) =>")
      indent += 1
      line(s"$className($ctorArgs);")
      indent -= 1
      blank()
      // toJson. A data field whose wire key collides with the sealed tag's
      // 'type' key is dropped from the literal — the discriminator wins,
      // mirroring json_serializable's `map['type'] = …` overwrite.
      if tag.isDefined then line("@override")
      line(s"Map<String, dynamic> toJson() => {")
      indent += 1
      for p <- all if !(tag.isDefined && jsonKeyOf(p) == "type") do
        line(s"'${jsonKeyOf(p)}': ${jsonEncodeExpr(p.tpt.tpe, p.name.toString)},")
      tag.foreach(t => line(s"'type': '$t',"))
      indent -= 1
      line("};")
      blank()

    /** The sealed parent's side of the codec: an abstract `toJson` and a
     *  `fromJson` factory dispatching on the `type` discriminator.
     */
    private def emitSealedJsonDispatch(className: String, sym: Symbol): Unit =
      line(s"static $className fromJson(Map<String, dynamic> json) {")
      indent += 1
      line("final String t = json['type'] as String;")
      for child <- sym.children do
        line(s"if (t == '${jsonTagOf(child)}') return ${child.name}.fromJson(json);")
      line("throw Exception('Unsupported type: ' + t);")
      indent -= 1
      line("}")
      blank()
      line("Map<String, dynamic> toJson();")
      blank()

    private def emitField(vd: ValDef, static: Boolean = false): Unit =
      val isMutable = vd.symbol.flags.is(Flags.Mutable)
      // `lazy val` fields → Dart `late final` (first-read initialization).
      val prefix = (if static then "static " else "") + {
        if vd.symbol.flags.is(Flags.Lazy) then "late final "
        else if isMutable then "" else "final "
      }
      val baseTpe = emitTypeRef(vd.tpt.tpe)
      // Null-initialised fields: Dart's sound null safety rejects
      // `Foo x = null`, so add a `?` to the type when the RHS is a
      // literal null (or omitted on a mutable field, which Dart would
      // also treat as null-default).
      val tpe = vd.rhs match
        case Some(Literal(c)) if c.value == null      => if baseTpe.endsWith("?") then baseTpe else baseTpe + "?"
        case None if isMutable && !baseTpe.endsWith("?") => baseTpe + "?"
        case _                                        => baseTpe
      val init = vd.rhs.map(r => s" = ${emitExpr(r)}").getOrElse("")
      line(s"$prefix$tpe ${vd.name}$init;")

    private def emitMethod(dd: DefDef, static: Boolean = false): Unit =
      val sym = dd.symbol
      if sym.flags.is(Flags.Synthetic) then return

      emitSourceAttribution(sym)
      if sym.flags.is(Flags.Override) && !static then line("@override")
      val staticPrefix = if static then "static " else ""

      val retType = emitTypeRef(dd.returnTpt.tpe)
      val params = dd.paramss.flatMap(_.params).collect { case vd: ValDef => vd }
      // Params with literal Scala defaults form a Dart named section
      // carrying the default; the rest stay positional.
      val shape = dartParamShape(dd.symbol, params)
      val posStr = shape.positional.map(p => s"${emitTypeRef(p.tpt.tpe)} ${dartSafeName(p.name)}")
      val nmdStr = shape.named.map((p, d) => s"${emitTypeRef(p.tpt.tpe)} ${dartSafeName(p.name)} = $d")
      val paramStr =
        if nmdStr.isEmpty then posStr.mkString(", ")
        else if posStr.isEmpty then nmdStr.mkString("{", ", ", "}")
        else posStr.mkString(", ") + ", " + nmdStr.mkString("{", ", ", "}")
      val tparams = typeParamSig(dd)

      // Scala paren-less `def foo: Int = …` → Dart getter `int get foo`.
      // Distinguishes from `def foo(): Int` (empty parens → Dart method).
      // Users' paren-less call sites `x.foo` work cleanly against a getter.
      val isGetter = dd.paramss.isEmpty

      dd.rhs match
        case Some(rawBody) =>
          val asyncWrapped = unwrapAsync(rawBody)
          val body    = asyncWrapped.getOrElse(rawBody)
          val isAsync = asyncWrapped.isDefined || containsAwait(body)
          val asyncMark = if isAsync then " async" else ""
          val header =
            if isGetter then s"$staticPrefix$retType get ${sym.name}$asyncMark {"
            else s"$staticPrefix$retType ${sym.name}$tparams($paramStr)$asyncMark {"
          line(header)
          indent += 1
          emitBodyAsStatements(body, returnLast = retType != "void")
          indent -= 1
          line("}")
          blank()
        case None =>
          if isGetter then line(s"$staticPrefix$retType get ${sym.name};")
          else line(s"$staticPrefix$retType ${sym.name}$tparams($paramStr);")

    /** Extract `[T <: Foo, U]`-style type parameters from a `DefDef`
     *  (including the primary constructor, which is how class-level type
     *  params surface in TASTy). Emits Dart `<T extends Foo, U>` form so
     *  bounds are preserved. Returns `""` when none.
     *
     *  Unbounded `T`s drop the `extends`. Scala's default upper bound of
     *  `Any` also drops the `extends` (Dart `Object?` is the equivalent
     *  and Dart's type inference handles it without the annotation).
     */
    private def typeParamSig(dd: DefDef): String =
      val tps: List[TypeDef] = dd.paramss.collect {
        case tpc: TypeParamClause => tpc.params
      }.flatten
      if tps.isEmpty then ""
      else
        val parts = tps.map { tp =>
          tp.rhs match
            case tb: TypeBoundsTree =>
              val upper = tb.hi.tpe
              val upperSym = upper.typeSymbol.fullName
              if upperSym == "scala.Any" || upperSym == "java.lang.Object" then tp.name
              else s"${tp.name} extends ${emitTypeRef(upper)}"
            case _ => tp.name
        }
        parts.mkString("<", ", ", ">")

    // ── Top-level defs & vals ────────────────────────────────────────────

    /** Emit a Scala 3 extension method as a Dart `extension` block with
     *  one member.
     *
     *  Scala shape:  `extension (n: Int) def squared: Int = n * n`
     *  TASTy shape:  DefDef `squared` with `Flags.ExtensionMethod`, whose first
     *                term-param-clause has a single ValDef (the receiver),
     *                and whose body may reference the receiver by name.
     *  Dart shape:   `extension SartIntSquared on int { int get squared {
     *                  final int n = this; return n * n; } }`
     *
     *  We inject `final T n = this;` as the first statement of the body so
     *  references to the receiver in the original body transfer unchanged.
     *  A future pass can rewrite refs to `this` directly and drop the alias.
     */
    private def emitExtensionMethod(dd: DefDef): Unit =
      val sym = dd.symbol
      val termClauses: List[List[ValDef]] = dd.paramss.collect {
        case tpc: TermParamClause => tpc.params
      }
      if termClauses.isEmpty then
        line(s"/* TODO extension $sym — no term params */")
        return

      val receiver = termClauses.head.headOption match
        case Some(vd: ValDef) => vd
        case _ =>
          line(s"/* TODO extension $sym — unexpected receiver shape */")
          return

      val methodParams = termClauses.drop(1).flatten
      val receiverTpe  = emitTypeRef(receiver.tpt.tpe)
      val retType      = emitTypeRef(dd.returnTpt.tpe)
      val tparams      = typeParamSig(dd)

      val extName = s"Sart${receiver.tpt.tpe.typeSymbol.name}${sym.name.capitalize}"
      // Type params go on the METHOD, not the extension — an extension's
      // own params only infer from the receiver, so `withLoader<T>` on
      // the extension would collapse to dynamic at every call.
      line(s"extension $extName on $receiverTpe {")
      indent += 1

      // A getter only when the Scala def is paren-less (no clause after
      // the receiver); `def feedback(): Unit` keeps its parens. Params
      // follow the same positional/named-default shape as methods.
      val isGetterExt = termClauses.drop(1).isEmpty
      val isAsync = dd.rhs.exists(containsAwait)
      val asyncMark = if isAsync then " async" else ""
      val methodHeader =
        if isGetterExt then
          s"$retType get ${sym.name}$asyncMark {"
        else
          // Extension default getters count the receiver clause, so the
          // param index is offset by one.
          val shape  = dartParamShape(sym, methodParams, idxOffset = 1)
          val posStr = shape.positional.map(p => s"${emitTypeRef(p.tpt.tpe)} ${dartSafeName(p.name)}")
          val nmdStr = shape.named.map((p, d) => s"${emitTypeRef(p.tpt.tpe)} ${dartSafeName(p.name)} = $d")
          val paramStr =
            if nmdStr.isEmpty then posStr.mkString(", ")
            else if posStr.isEmpty then nmdStr.mkString("{", ", ", "}")
            else posStr.mkString(", ") + ", " + nmdStr.mkString("{", ", ", "}")
          s"$retType ${sym.name}$tparams($paramStr)$asyncMark {"
      line(methodHeader)
      indent += 1
      line(s"final $receiverTpe ${receiver.name} = this;")
      dd.rhs match
        case Some(body) => emitBodyAsStatements(body, returnLast = retType != "void")
        case None       => ()
      indent -= 1
      line("}")

      indent -= 1
      line("}")
      blank()

    private def emitTopLevelDef(dd: DefDef): Unit =
      val sym = dd.symbol
      if sym.flags.is(Flags.Synthetic) then return

      // `@main def foo` → emit as Dart `void main()`.
      val mainFqns = Set("scala.main", "scala.annotation.newMain", "scala.annotation.main")
      val isMainAnnotated = sym.annotations.exists(a => mainFqns.contains(annoFqn(a)))
      if isMainAnnotated then
        dd.rhs match
          case Some(body) =>
            emitSourceAttribution(sym)
            line("void main() {")
            indent += 1
            emitBodyAsStatements(body, returnLast = false)
            indent -= 1
            line("}")
            blank()
          case None => ()
        return

      // Regular top-level `def` (including `inline def`, since Scala 3's
      // TASTy retains the uninlined form when the call site is in the same
      // compilation unit). Emit as a Dart top-level function.
      val retType = emitTypeRef(dd.returnTpt.tpe)
      val params  = dd.paramss.flatMap(_.params).collect { case vd: ValDef => vd }
      val paramStr = params.map(p => s"${emitTypeRef(p.tpt.tpe)} ${dartSafeName(p.name)}").mkString(", ")
      val tparams  = typeParamSig(dd)
      emitSourceAttribution(sym)
      dd.rhs match
        case Some(body) =>
          line(s"$retType ${sym.name}$tparams($paramStr) {")
          indent += 1
          emitBodyAsStatements(body, returnLast = retType != "void")
          indent -= 1
          line("}")
          blank()
        case None =>
          line(s"$retType ${sym.name}$tparams($paramStr);")

    private def emitTopLevelVal(vd: ValDef): Unit =
      val sym = vd.symbol
      if sym.flags.is(Flags.Synthetic) then return
      val typeSym = vd.tpt.tpe.typeSymbol
      // Case-object singleton val: `case object UnitSquare` creates both a
      // module class `UnitSquare$` and a val `UnitSquare` of that type.
      // We emit the case-object as a plain Dart class (`class UnitSquare`)
      // via `emitCaseObject`, which IS the Dart identity — the pointer
      // val has no meaning in Dart and would just dangle.
      if typeSym.flags.is(Flags.Case) && typeSym.flags.is(Flags.Module) then return
      // The pointer val behind a plain user `object` (emitted as a Dart
      // class of statics) has no Dart meaning either — only `given`
      // singletons keep their value binding.
      if typeSym.flags.is(Flags.Module) && !sym.flags.is(Flags.Given) then return
      // For a val whose static type is a module class (e.g. the synthesised
      // singleton behind `given intFormatter: Formatter[Int] with { … }`)
      // widen to the first real parent, so the Dart variable references
      // the *abstraction* (`Formatter<int>`) rather than the internal
      // module class name.
      val renderedType = emitTypeRef(declaredTypeFor(vd.tpt.tpe))
      val prefix = if sym.flags.is(Flags.Mutable) then "" else "final "
      val init = vd.rhs.map(r => s" = ${emitExpr(r)}").getOrElse("")
      emitSourceAttribution(sym)
      line(s"$prefix$renderedType ${vd.name}$init;")
      blank()

    /** When `tpe` is a module-class singleton, widen to the first non-trivial
     *  parent (skipping Object/Product/Serializable/DartObject). For other
     *  types, returns `tpe` unchanged.
     */
    private def declaredTypeFor(tpe: TypeRepr): TypeRepr =
      val sym = tpe.typeSymbol
      if !sym.flags.is(Flags.Module) then tpe
      else
        val parentSym = tpe.baseClasses.drop(1).find { bc =>
          !skippedParentFqns(bc.fullName) && !skippedParentSimples(bc.name)
        }
        parentSym.map(tpe.baseType).getOrElse(tpe)

    // ── Body emission ────────────────────────────────────────────────────

    /** Emit a tree as a sequence of Dart statements. When `returnLast` is
     *  true, the final expression is prefixed with `return`.
     */
    private def emitBodyAsStatements(t: Tree, returnLast: Boolean): Unit = t match
      // A body that IS a lambda — `def redirect = (c, s) => …` — arrives
      // as Block(List(DefDef), Closure). Route it through the expression
      // path whole, before the generic Block split would tear it apart.
      case b @ Block(List(_: DefDef), _: Closure) =>
        emitTerminal(b, returnLast)
      // Temp-val desugar at body position — route through the expression
      // path so the block-inliner collapses the synthetic `val xN$M = …`
      // hoisting into a single call. Without this, method bodies that
      // construct a widget tree with a mix of named+default args emit with
      // an ugly prelude of intermediate vals.
      case block @ Block(stats, expr: Term)
        if stats.nonEmpty && stats.forall { case _: ValDef => true; case _ => false }
           && !isStatementOnlyTerm(expr) =>
        emitTerminal(block, returnLast)
      case Block(stats, expr) =>
        stats.foreach(emitStmt)
        emitTerminal(expr, returnLast)
      case tryTree: Try =>
        emitTryStatement(tryTree, returnLast)
      case other: Term =>
        emitTerminal(other, returnLast)
      case other =>
        line(s"/* TODO body ${other.getClass.getSimpleName} */")

    /** Emit `try { … } on E catch (e) { … } finally { … }` as a Dart
     *  statement. Each catch-clause body is itself dispatched back through
     *  `emitBodyAsStatements`, so `return` still lands correctly when this
     *  Try is the tail of a non-Unit method.
     */
    private def emitTryStatement(t: Try, returnLast: Boolean): Unit =
      line("try {")
      indent += 1
      emitBodyAsStatements(t.body, returnLast)
      indent -= 1

      for c <- t.cases do
        val header = c.pattern match
          // `case _: E => …`                 → `on E { … }`
          case Typed(Ident("_"), tpt) =>
            s"} on ${emitTypeRef(tpt.tpe)} {"
          // `case e: E => …`                 → `on E catch (e) { … }`  (or
          // `on E {` when the body doesn't use `e`; keeps Dart's
          // `unused_catch_clause` lint quiet.)
          case Bind(name, Typed(Ident("_"), tpt)) =>
            val t = emitTypeRef(tpt.tpe)
            if bodyUsesIdent(c.rhs, name) then s"} on $t catch ($name) {"
            else s"} on $t {"
          // `case e => …` (type inferred)   → `catch (e) { … }`
          case Bind(name, Ident("_")) =>
            if bodyUsesIdent(c.rhs, name) then s"} catch ($name) {"
            else s"} catch (_) {"
          case Ident("_") =>
            s"} catch (_) {"
          case _ =>
            s"} catch (_) { /* TODO complex catch pattern */"
        line(header)
        indent += 1
        emitBodyAsStatements(c.rhs, returnLast)
        indent -= 1

      t.finalizer match
        case Some(body) =>
          line("} finally {")
          indent += 1
          emitBodyAsStatements(body, returnLast = false)
          indent -= 1
          line("}")
        case None =>
          line("}")

    private def emitTerminal(t: Tree, returnLast: Boolean): Unit = t match
      // Wrappers are transparent — unwrap so statement-only constructs
      // (Unit `if`, `try`, `match`) are recognized beneath them.
      case Typed(inner: Term, _)      => emitTerminal(inner, returnLast)
      case Inlined(_, _, inner: Term) => emitTerminal(inner, returnLast)
      case Literal(c) if c.value == () =>
        () // nothing to emit; a Unit-valued body trails off
      case w: While =>
        emitStmt(w) // a while loop is Unit-valued; nothing to return
      // A Unit-typed trailing `if` stays a statement — returning a
      // void-operand ternary is invalid Dart.
      case ifTerm @ If(_, _, _) if isUnitTyped(ifTerm) =>
        emitStmt(ifTerm)
      // A Unit-typed trailing `match` stays a statement — a Dart switch
      // *expression* with void arms is invalid.
      case m @ Match(_, _) if isUnitTyped(m) =>
        emitStmt(m)
      // A trailing try/catch renders as the statement form.
      case tryTree: Try =>
        emitTryStatement(tryTree, returnLast)
      case term: Term =>
        if returnLast then line(s"return ${emitExpr(term)};")
        else line(s"${emitExpr(term)};")
      case _ =>
        line(s"/* TODO terminal ${t.getClass.getSimpleName} */")

    private def emitStmt(t: Tree): Unit = t match
      case vd: ValDef =>
        // `lazy val` → Dart `late final`: the initializer runs on first
        // read, which is exactly Scala's (single-threaded) lazy semantics.
        val isNullInit = vd.rhs.exists {
          case Literal(c) => c.value == null
          case _          => false
        }
        val init = vd.rhs.map(r => s" = ${emitExpr(r)}").getOrElse("")
        if vd.symbol.flags.is(Flags.Lazy) then
          line(s"late final ${emitTypeRef(vd.tpt.tpe)} ${vd.name}$init;")
        else if !vd.symbol.flags.is(Flags.Mutable) && vd.rhs.nonEmpty && !isNullInit then
          // Immutable local with an initializer: let Dart infer the type.
          // Inference keeps nullability honest (a read of a nullable field
          // infers `T?`), which is what makes null-check promotion work —
          // Dart never promotes fields, only locals.
          line(s"final ${vd.name}$init;")
        else
          val declared = emitTypeRef(vd.tpt.tpe)
          val tpe = if isNullInit && !declared.endsWith("?") && declared != "dynamic" then declared + "?" else declared
          line(s"${if vd.symbol.flags.is(Flags.Mutable) then "" else "final "}$tpe ${vd.name}$init;")
      case Assign(lhs, rhs) =>
        line(s"${emitExpr(lhs)} = ${emitExpr(rhs)};")
      case tryTree: Try =>
        emitTryStatement(tryTree, returnLast = false)
      case While(cond, body) =>
        line(s"while (${emitExpr(cond)}) {")
        indent += 1
        emitBodyAsStatements(body, returnLast = false)
        indent -= 1
        line("}")
      // Unit-typed `if` at statement position — a real Dart `if`
      // statement; a ternary with void operands is invalid Dart.
      case ifTerm @ If(cond, thenp, elsep) if isUnitTyped(ifTerm) =>
        line(s"if (${emitExpr(cond)}) {")
        indent += 1
        emitBodyAsStatements(thenp, returnLast = false)
        indent -= 1
        if isUnitLiteral(elsep) then line("}")
        else
          line("} else {")
          indent += 1
          emitBodyAsStatements(elsep, returnLast = false)
          indent -= 1
          line("}")
      // Unit-typed `match` at statement position — a Dart switch
      // *statement* with `case pattern:` labels (Dart 3 has no implicit
      // fall-through; an empty arm gets an explicit `break` so it doesn't
      // merge with the next label).
      case m @ Match(scrutinee, cases) if isUnitTyped(m) =>
        line(s"switch (${emitExpr(scrutinee)}) {")
        indent += 1
        cases.foreach { c =>
          val usageScope: Tree = c.guard match
            case Some(g) => Block(List(g), c.rhs)
            case None    => c.rhs
          val pat   = emitPattern(c.pattern, usageScope)
          val guard = c.guard.map(g => s" when ${emitExpr(g)}").getOrElse("")
          line(s"case $pat$guard:")
          indent += 1
          if isUnitLiteral(c.rhs) then line("break;")
          else emitBodyAsStatements(c.rhs, returnLast = false)
          indent -= 1
        }
        indent -= 1
        line("}")
      case term: Term =>
        line(s"${emitExpr(term)};")
      case _: DefDef =>
        // Nested defs (e.g. lambda-lifted) shouldn't appear at statement
        // position in the subset we support.
        line(s"/* TODO nested def */")
      case _ =>
        line(s"/* TODO stmt ${t.getClass.getSimpleName} */")

    // ── Expressions ──────────────────────────────────────────────────────

    private def emitExpr(t: Term): String = t match
      case Literal(c) => emitConstant(c)
      // Hand-ported stdlib singletons — must precede the generic `Ident` /
      // `Select` fallbacks or those would swallow the reference.
      case t if isSartRef(t, "sart.stdlib.None") => "null"
      case t if isSartRef(t, "scala.None") => "null"
      // `Double.PositiveInfinity` → `double.infinity` (`width: double.infinity`
      // is the Flutter fill-the-parent idiom).
      case Select(Ident("Double"), "PositiveInfinity") => "double.infinity"
      case Select(Ident("Double"), "NegativeInfinity") => "double.negativeInfinity"
      case Select(Ident("Double"), "NaN")              => "double.nan"
      case Ident(name) => dartSafeName(name)
      case This(_) => "this"
      case _: Super => "super"

      // Scala's Predef auto-inserts implicit wrappers (`augmentString(s)`,
      // `intWrapper(n)`, etc.) so its stdlib-style methods/operators are
      // reachable. Dart's native `String`/`int`/`double` provide equivalent
      // operators directly, so we strip the wrapper and emit just the
      // underlying argument. This case has to run before the generic
      // `Apply(Select(qual, name), args)` branch would otherwise emit
      // `Predef.augmentString(s)` literally.
      case Apply(fn, List(arg)) if isScalaImplicitWrapper(fn) =>
        emitExpr(arg)
      case Apply(TypeApply(fn, _), List(arg)) if isScalaImplicitWrapper(fn) =>
        emitExpr(arg)

      // s"..." → Dart single-quoted string with $x / ${e} interpolation.
      // The qualifier of `.s(args*)` is a StringContext construction; we
      // accept several tree shapes the compiler may produce.
      case Apply(Select(qual, "s"), args) if stringContextParts(qual).nonEmpty =>
        val parts = stringContextParts(qual)
        val actualArgs = args match
          case List(Typed(Repeated(items, _), _)) => items
          case List(Repeated(items, _))           => items
          case other                              => other
        emitInterpolationParts(parts, actualArgs)

      // List(a, b, ...) → [a, b, ...]. An EMPTY `List()` keeps its element
      // type (`<Widget>[]`) — a bare `[]` is List<dynamic>, which poisons
      // `+`-concatenation chains feeding List<Widget> parameters.
      case Apply(TypeApply(Select(Ident("List"), "apply"), List(tpt)), List(arg)) if isVarargs(arg) =>
        val items = varargsItems(arg)
        if items.isEmpty then s"<${emitTypeRef(tpt.tpe)}>[]"
        else items.map(emitExpr).mkString("[", ", ", "]")
      case Apply(Select(Ident("List"), "apply"), List(arg)) if isVarargs(arg) =>
        varargsItems(arg).map(emitExpr).mkString("[", ", ", "]")

      // (a, b, ...) — tuple literals desugar to `Tuple<N>.apply(a, b, ...)`
      // in TASTy. Emit Dart record literals `(a, b, ...)`.
      case Apply(TypeApply(Select(Ident(name), "apply"), _), args)
        if name.matches("Tuple\\d+") =>
        args.map(emitExpr).mkString("(", ", ", ")")
      case Apply(Select(Ident(name), "apply"), args)
        if name.matches("Tuple\\d+") =>
        args.map(emitExpr).mkString("(", ", ", ")")

      // Set(a, b, ...) → {a, b, ...}  (Dart set literal; empty `Set()` →
      // `<dynamic>{}` would be ambiguous with a Map, so we fall through
      // to the generic path when empty.)
      case Apply(TypeApply(Select(Ident("Set"), "apply"), _), List(arg)) if varargsItems(arg).nonEmpty =>
        varargsItems(arg).map(emitExpr).mkString("{", ", ", "}")
      case Apply(Select(Ident("Set"), "apply"), List(arg)) if varargsItems(arg).nonEmpty =>
        varargsItems(arg).map(emitExpr).mkString("{", ", ", "}")

      // Map("a" -> 1, "b" -> 2) → {'a': 1, 'b': 2}  (Dart map literal).
      // Scala compiles `"a" -> 1` to an `ArrowAssoc.->` call, which we
      // unwrap to `key: value` pairs.
      // Empty `Map()` keeps its type args (`<String, int>{}`) — a bare
      // `{}` would be Map<dynamic, dynamic> (or a set literal).
      case Apply(TypeApply(Select(Ident("Map"), "apply"), List(k, v)), List(arg)) if varargsItems(arg).isEmpty =>
        s"<${emitTypeRef(k.tpe)}, ${emitTypeRef(v.tpe)}>{}"
      case Apply(TypeApply(Select(Ident("Map"), "apply"), _), List(arg)) if varargsItems(arg).nonEmpty =>
        varargsItems(arg).flatMap(mapEntry).mkString("{", ", ", "}")
      case Apply(Select(Ident("Map"), "apply"), List(arg)) if varargsItems(arg).nonEmpty =>
        varargsItems(arg).flatMap(mapEntry).mkString("{", ", ", "}")

      // `new Foo(args)` → `Foo(args)`. For facade classes (@native) we keep
      // Scala named args as Dart named args (Dart constructor is named-form).
      // For user classes we strip names — the emitted Dart ctor is positional.
      case Apply(Select(New(tpt), _), args) =>
        recordAnnotations(tpt.tpe.typeSymbol)
        val ctorName = ctorTypeName(tpt.tpe)
        val argStr =
          if hasNative(tpt.tpe.typeSymbol) then emitArgs(args)
          else emitUserCallArgs(tpt.tpe.typeSymbol.primaryConstructor, args)
        s"$ctorName($argStr)"
      case Apply(TypeApply(Select(New(tpt), _), targs), args) =>
        recordAnnotations(tpt.tpe.typeSymbol)
        // Generic creator application: `GlobalKey[FormState]()` carries
        // its type args on the TypeApply — keep them (`GlobalKey<FormState>()`)
        // so Dart doesn't infer a wider type.
        val ctorName = tpt.tpe match
          case AppliedType(_, _) => emitTypeRef(tpt.tpe)
          case _ if targs.nonEmpty =>
            s"${dartName(tpt.tpe.typeSymbol)}<${targs.map(t => emitTypeRef(t.tpe)).mkString(", ")}>"
          case _ => dartName(tpt.tpe.typeSymbol)
        val argStr =
          if hasNative(tpt.tpe.typeSymbol) then emitArgs(args)
          else emitUserCallArgs(tpt.tpe.typeSymbol.primaryConstructor, args)
        s"$ctorName($argStr)"

      // Json bridge: Scala-side entry points to the synthesized @JsonModel
      // codecs. `Json.decode[T](d)` → `T.fromJson(d as Map<String, dynamic>)`;
      // `Json.encode(x)` → `x.toJson()`.
      case Apply(TypeApply(Select(q, "decode"), List(tpt)), List(arg)) if isSartRef(q, "sart.dart.Json") =>
        s"${tpt.tpe.typeSymbol.name}.fromJson(${emitExpr(arg)} as Map<String, dynamic>)"
      case Apply(Select(q, "encode"), List(arg)) if isSartRef(q, "sart.dart.Json") =>
        s"${emitExpr(arg)}.toJson()"

      // `nn(x)` → `x!` — Dart's non-null assertion, for facade members
      // that are nullable on the Dart side.
      case Apply(TypeApply(Select(q, "apply"), _), List(arg)) if isSartRef(q, "sart.dart.nn") =>
        s"${emitExpr(arg)}!"
      case Apply(Select(q, "apply"), List(arg)) if isSartRef(q, "sart.dart.nn") =>
        s"${emitExpr(arg)}!"

      // `cast[T](x)` → `(x as T)`.
      case Apply(TypeApply(Select(q, "apply"), List(t)), List(arg)) if isSartRef(q, "sart.dart.cast") =>
        s"(${emitExpr(arg)} as ${emitTypeRef(t.tpe)})"

      // `x.isInstanceOf[T]` → `x is T`; `x.asInstanceOf[T]` → `(x as T)`.
      case TypeApply(Select(recv, "isInstanceOf"), List(t)) =>
        s"${emitExpr(recv)} is ${emitTypeRef(t.tpe)}"
      case TypeApply(Select(recv, "asInstanceOf"), List(t)) =>
        s"(${emitExpr(recv)} as ${emitTypeRef(t.tpe)})"
      case Apply(TypeApply(Select(recv, "isInstanceOf"), List(t)), Nil) =>
        s"${emitExpr(recv)} is ${emitTypeRef(t.tpe)}"
      case Apply(TypeApply(Select(recv, "asInstanceOf"), List(t)), Nil) =>
        s"(${emitExpr(recv)} as ${emitTypeRef(t.tpe)})"

      // `Futures.ensure(f, action)` → `f.whenComplete(action)` — the
      // try/finally of futures.
      case Apply(TypeApply(Select(q, "ensure"), _), List(f, action)) if isSartRef(q, "sart.dart.Futures") =>
        s"${emitExpr(f)}.whenComplete(${emitExpr(action)})"
      case Apply(Select(q, "ensure"), List(f, action)) if isSartRef(q, "sart.dart.Futures") =>
        s"${emitExpr(f)}.whenComplete(${emitExpr(action)})"
      case Apply(TypeApply(Select(q, "onError"), _), List(f, handler)) if isSartRef(q, "sart.dart.Futures") =>
        s"${emitExpr(f)}.catchError(${emitExpr(handler)})"
      case Apply(Select(q, "onError"), List(f, handler)) if isSartRef(q, "sart.dart.Futures") =>
        s"${emitExpr(f)}.catchError(${emitExpr(handler)})"
      case Apply(Select(q, "delayed"), List(d, body)) if isSartRef(q, "sart.dart.Futures") =>
        s"Future.delayed(${emitExpr(d)}, ${emitExpr(body)})"
      case Apply(Select(q, "microtask"), List(body)) if isSartRef(q, "sart.dart.Futures") =>
        s"Future.microtask(${emitExpr(body)})"

      // `await(f)` → `(await f)` — the enclosing emitted function is
      // marked `async` by containsAwait detection in emitMethod/emitClosure.
      case Apply(TypeApply(Select(q, "apply"), _), List(f)) if isSartRef(q, "sart.dart.await") =>
        s"(await ${emitExpr(f)})"
      case Apply(Select(q, "apply"), List(f)) if isSartRef(q, "sart.dart.await") =>
        s"(await ${emitExpr(f)})"

      // `async { body }` in expression position → immediately-invoked
      // async closure. (Whole-method `= async { … }` bodies are unwrapped
      // in emitMethod instead.)
      case Apply(TypeApply(Select(q, "apply"), _), List(body)) if isSartRef(q, "sart.dart.async") =>
        s"(() async { ${stmtInline(body)} })()"
      case Apply(Select(q, "apply"), List(body)) if isSartRef(q, "sart.dart.async") =>
        s"(() async { ${stmtInline(body)} })()"

      // Extension-method calls: `context.withLoader(msg, body)` compiles
      // to `withLoader(context)(msg, body)` (receiver clause first, type
      // params in varying positions). Emit as a Dart extension-method
      // call on the receiver.
      case Apply(Apply(fn, List(recv)), args) if isExtensionRef(fn) =>
        recordAnnotations(extensionSym(fn))
        s"${emitExpr(recv)}.${extensionCallName(fn)}(${emitUserCallArgs(extensionSym(fn), args, dropParams = 1)})"
      case Apply(TypeApply(Apply(fn, List(recv)), _), args) if isExtensionRef(fn) =>
        recordAnnotations(extensionSym(fn))
        s"${emitExpr(recv)}.${extensionCallName(fn)}(${emitUserCallArgs(extensionSym(fn), args, dropParams = 1)})"
      case Apply(Apply(TypeApply(fn, _), List(recv)), args) if isExtensionRef(fn) =>
        recordAnnotations(extensionSym(fn))
        s"${emitExpr(recv)}.${extensionCallName(fn)}(${emitUserCallArgs(extensionSym(fn), args, dropParams = 1)})"

      // Parameterless extension defs (`s.codeUnits`) — the receiver clause
      // is the only argument list, and Dart-side these are getters.
      case Apply(fn, List(recv)) if isExtensionRef(fn)
          && extensionSym(fn).paramSymss.count(_.exists(_.isTerm)) == 1 =>
        recordAnnotations(extensionSym(fn))
        s"${selectPrefix(recv)}${extensionCallName(fn)}"

      // `opt match { case Some(v) => a; case None => b }` — Dart has no
      // Option, so the match lowers to a null-check on a promoted local
      // named after the binder.
      case m @ Match(scrut, cases) if isOptionReceiver(scrut) && optionMatchArms(cases).isDefined =>
        val (binder, someRhs, noneRhs) = optionMatchArms(cases).get
        val asyncMark = if containsAwait(m) then " async" else ""
        val invoke = s"(()$asyncMark { final $binder = ${emitExpr(scrut)}; if ($binder != null) { return ${emitExpr(someRhs)}; } return ${emitExpr(noneRhs)}; })()"
        if asyncMark.isEmpty then invoke else s"(await $invoke)"

      // `sart.stdlib.Some(x)` → just `x` — Dart promotes the non-null value
      // into the nullable type automatically.
      case Apply(Select(qual, "apply"), args) if isSartRef(qual, "sart.stdlib.Some") || isSartRef(qual, "scala.Some") =>
        args.headOption.map(emitExpr).getOrElse("null")
      case Apply(TypeApply(Select(qual, "apply"), _), args) if isSartRef(qual, "sart.stdlib.Some") || isSartRef(qual, "scala.Some") =>
        args.headOption.map(emitExpr).getOrElse("null")

      // `Todo.apply(x, y)` on a case-class companion → `Todo(x, y)`. Scala
      // compiles `Foo(args)` (no `new`) into a call to the companion's
      // synthesised `apply`; Dart has no apply-on-companion concept, so we
      // rewrite it to the positional constructor.
      case Apply(Select(qual, "apply"), args) if isCaseClassCompanion(qual) =>
        val ctorName = caseClassNameFor(qual)
        s"$ctorName(${emitUserCallArgs(companionClassCtor(qual), args)})"
      case Apply(TypeApply(Select(qual, "apply"), _), args) if isCaseClassCompanion(qual) =>
        val ctorName = caseClassNameFor(qual)
        s"$ctorName(${emitUserCallArgs(companionClassCtor(qual), args)})"

      // `opt.getOrElse(d)` → `(opt ?? (d))` — Dart's null-coalescing
      // operator is the exact native equivalent. The default is
      // parenthesized: `a ?? cond ? x : y` would parse as `(a ?? cond) ? …`.
      case Apply(Select(recv, "getOrElse"), List(arg)) if isOptionReceiver(recv) =>
        val r = emitExpr(recv)
        val rp = if needsParensAsReceiver(recv) then s"($r)" else r
        s"($rp ?? (${emitExpr(arg)}))"
      case Apply(TypeApply(Select(recv, "getOrElse"), _), List(arg)) if isOptionReceiver(recv) =>
        val r = emitExpr(recv)
        val rp = if needsParensAsReceiver(recv) then s"($r)" else r
        s"($rp ?? (${emitExpr(arg)}))"

      // Presence checks → Dart null-comparison. Handles both getter-style
      // `Select` and zero-arg `Apply(Select(...), Nil)` tree shapes.
      case Select(recv, "isDefined") if isOptionReceiver(recv) => s"(${emitExpr(recv)} != null)"
      case Select(recv, "isEmpty")   if isOptionReceiver(recv) => s"(${emitExpr(recv)} == null)"
      case Select(recv, "nonEmpty")  if isOptionReceiver(recv) => s"(${emitExpr(recv)} != null)"
      case Apply(Select(recv, "isDefined"), Nil) if isOptionReceiver(recv) => s"(${emitExpr(recv)} != null)"
      case Apply(Select(recv, "isEmpty"),   Nil) if isOptionReceiver(recv) => s"(${emitExpr(recv)} == null)"
      case Apply(Select(recv, "nonEmpty"),  Nil) if isOptionReceiver(recv) => s"(${emitExpr(recv)} != null)"

      // `opt.get` → `recv!` — Dart's non-null assertion IS Option.get's
      // contract (throws on absence).
      case Select(recv, "get") if isOptionReceiver(recv) => s"${emitExpr(recv)}!"
      case Apply(Select(recv, "get"), Nil) if isOptionReceiver(recv) => s"${emitExpr(recv)}!"

      // `opt.orNull` — identity: Option[T] already IS `T?` in Dart. The
      // one-arg Apply shape is scala.Option's `orNull(implicit ev)`.
      case Select(recv, "orNull") if isOptionReceiver(recv) => emitExpr(recv)
      case TypeApply(Select(recv, "orNull"), _) if isOptionReceiver(recv) => emitExpr(recv)
      case Apply(Select(recv, "orNull"), Nil) if isOptionReceiver(recv) => emitExpr(recv)
      case Apply(TypeApply(Select(recv, "orNull"), _), Nil) if isOptionReceiver(recv) => emitExpr(recv)
      case Apply(TypeApply(Select(recv, "orNull"), _), List(_)) if isOptionReceiver(recv) => emitExpr(recv)

      // (`sart.stdlib.None` is handled at the top of `emitExpr` — before
      //  the generic `Ident` fallback — so a bare `None` reference lands
      //  as `null`.)

      // Closure: Block(List(DefDef), Closure) — zero-arg `() => expr` or
      // `() => { stmts; expr }`.
      case Block(List(dd: DefDef), _: Closure) =>
        emitClosure(dd)

      // A Block with no statements is just a wrapper around the trailing
      // expression — pass through. Scala 3 compiles `case x => 0` into
      // `Block(Nil, Literal(0))` for tree uniformity, so this unwrap is
      // what makes pattern-match arms land as clean Dart expressions.
      case Block(Nil, expr) =>
        emitExpr(expr)

      // Block with actual statements in expression position. The common
      // shape is a Scala desugar that hoists constructor arguments into
      // temp vals so default-arg / evaluation-order rules are satisfied.
      // We inline each val back into the trailing expression by string
      // substitution post-emission. Refs to vals whose RHS is a default-arg
      // synthesiser (`Foo.$lessinit$greater$default$N`) are marked and then
      // stripped from the emitted arg list.
      case Block(stats, expr: Term) if stats.nonEmpty && stats.forall { case _: ValDef => true; case _ => false } =>
        inlineTempValBlock(stats.collect { case vd: ValDef => vd }, expr)

      // Blocks with non-ValDef statements (e.g. inner defs, assignments) —
      // fall back to an immediately-invoked closure. Valid Dart; less clean
      // than the temp-val inliner but correct. Awaits inside make the
      // closure async and the invocation awaited.
      case Block(stats, expr) =>
        val hasAwait = stats.exists(containsAwait) || (expr match
          case t: Term => containsAwait(t)
          case _       => false)
        val asyncMark = if hasAwait then " async" else ""
        val sb = new StringBuilder(s"(()$asyncMark { ")
        stats.foreach { s =>
          sb.append(stmtInline(s))
          sb.append(' ')
        }
        expr match
          case Literal(c) if c.value == () => ()
          case term: Term if isUnitTyped(term) => sb.append(stmtInline(term)).append(' ')
          case term: Term => sb.append("return ").append(emitExpr(term)).append("; ")
          case _          => ()
        sb.append("})()")
        if hasAwait then s"(await ${sb.toString})" else sb.toString

      // String concatenation: in Scala `"x" + 42` calls `String.+` which
      // silently coerces; in Dart the `+` on String requires a String rhs,
      // so we wrap non-string operands in `.toString()` on the way through.
      // Match both sides to catch `"x" + n` and `n + "x"`.
      case Apply(Select(lhs, "+"), List(rhs)) if isStringType(lhs.tpe) || isStringType(rhs.tpe) =>
        // Operands binding looser than `+` (ternaries from if-expressions)
        // need parens; nested `+` chains don't.
        def loose(t: Term): Boolean = t match
          case If(_, _, _) | Match(_, _) | Assign(_, _) => true
          case Typed(e, _)                              => loose(e)
          case Inlined(_, _, e)                         => loose(e)
          case Block(Nil, e: Term)                      => loose(e)
          case _                                        => false
        def side(t: Term): String =
          val e = emitExpr(t)
          val wrapped = if loose(t) then s"($e)" else e
          if isStringType(t.tpe) then wrapped else s"$wrapped.toString()"
        s"${side(lhs)} + ${side(rhs)}"

      // List append `xs :+ x` → Dart spread `[...xs, x]`. Dart lacks a
      // native append operator but the spread literal is idiomatic.
      case Apply(Select(lhs, name), List(rhs)) if isListLikeReceiver(lhs) && (name == ":+" || name == "appended") =>
        s"[...${emitExpr(lhs)}, ${emitExpr(rhs)}]"
      // List prepend `x +: xs` → `[x, ...xs]`.
      case Apply(Select(lhs, name), List(rhs)) if isListLikeReceiver(lhs) && (name == "+:" || name == "prepended") =>
        s"[${emitExpr(rhs)}, ...${emitExpr(lhs)}]"
      case Apply(TypeApply(Select(lhs, name), _), List(rhs)) if isListLikeReceiver(lhs) && (name == ":+" || name == "appended") =>
        s"[...${emitExpr(lhs)}, ${emitExpr(rhs)}]"
      case Apply(TypeApply(Select(lhs, name), _), List(rhs)) if isListLikeReceiver(lhs) && (name == "+:" || name == "prepended") =>
        s"[${emitExpr(rhs)}, ...${emitExpr(lhs)}]"

      // `xs(i)` (index access) → `xs[i]`.
      case Apply(Select(recv, "apply"), List(idx)) if isListLikeReceiver(recv) =>
        s"${emitExpr(recv)}[${emitExpr(idx)}]"

      // `xs.updated(i, x)` → `[...xs.sublist(0, i), x, ...xs.sublist(i+1)]`.
      // Scala List is immutable; we produce a fresh Dart list with the
      // element at index `i` replaced.
      case Apply(Select(recv, "updated"), List(idx, value)) if isListLikeReceiver(recv) =>
        val r = emitExpr(recv); val i = emitExpr(idx); val v = emitExpr(value)
        s"[...$r.sublist(0, $i), $v, ...$r.sublist($i + 1)]"
      case Apply(TypeApply(Select(recv, "updated"), _), List(idx, value)) if isListLikeReceiver(recv) =>
        val r = emitExpr(recv); val i = emitExpr(idx); val v = emitExpr(value)
        s"[...$r.sublist(0, $i), $v, ...$r.sublist($i + 1)]"

      // Binary operator: `a + b`, `a == b`, etc. Parenthesize operands
      // that are themselves binary ops (or `if`/`match`/assignment) so
      // Dart's operator precedence matches Scala's grouping — otherwise
      // `(x + 1) % y` silently emits as `x + 1 % y` and reparses as
      // `x + (1 % y)`.
      // Bitwise/shift operators — Dart and Scala disagree on their
      // precedence relative to comparisons, so the whole expression is
      // always parenthesized.
      case Apply(Select(lhs, op), List(rhs)) if Set("<<", ">>", ">>>", "&", "|", "^").contains(op) =>
        val l = emitExpr(lhs); val r = emitExpr(rhs)
        val lp = if needsParensAsReceiver(lhs) then s"($l)" else l
        val rp = if needsParensAsReceiver(rhs) then s"($r)" else r
        s"($lp $op $rp)"

      case Apply(Select(lhs, op), List(rhs)) if isBinaryOp(op) =>
        val l = emitExpr(lhs); val r = emitExpr(rhs)
        val lp = if needsParensAsReceiver(lhs) then s"($l)" else l
        val rp = if needsParensAsReceiver(rhs) then s"($r)" else r
        // Scala's Int/Int division IS integer division; Dart's `/` always
        // produces a double — `~/` is the semantic match.
        val dartOp =
          if op == "/" && lhs.tpe.typeSymbol.fullName == "scala.Int"
             && rhs.tpe.typeSymbol.fullName == "scala.Int" then "~/"
          else op
        s"$lp ${dartOp} $rp"

      // `runApp.apply(arg)` — the `@native` singleton pattern for top-level
      // Dart functions. Emit as a bare call. Second case covers generic
      // apply like `Right.apply[L, R](x)` where TASTy wraps in TypeApply.
      case Apply(Select(idQual, "apply"), args) if isNativeSingleton(idQual) =>
        val fn = dartName(idQual.tpe.termSymbol)
        recordAnnotations(idQual.tpe.termSymbol)
        s"$fn(${emitArgs(args)})"
      case Apply(TypeApply(Select(idQual, "apply"), _), args) if isNativeSingleton(idQual) =>
        val fn = dartName(idQual.tpe.termSymbol)
        recordAnnotations(idQual.tpe.termSymbol)
        s"$fn(${emitArgs(args)})"

      // Curried call flattening. Scala lets methods have multiple value
      // parameter lists (`def fold(z)(f)`), and call sites mirror the
      // shape: `xs.fold(0)(f)`. Dart has no curried calls, so we collapse
      // each nested `Apply(Apply(inner, args1), args2)` to a single call
      // `inner(args1 ++ args2)`. Applies to direct method calls only —
      // cases where `f(x)(y)` really is a function-returning-function get
      // rewritten as wrong code, but the method-call shape covers 99%
      // of real Scala code.
      case Apply(Apply(sel @ Select(qual, name), args1), args2) =>
        recordAnnotations(qual.tpe.typeSymbol)
        emitMemberCall(qual, name, args1 ++ args2, sel.symbol)
      case Apply(Apply(TypeApply(sel @ Select(qual, name), _), args1), args2) =>
        recordAnnotations(qual.tpe.typeSymbol)
        emitMemberCall(qual, name, args1 ++ args2, sel.symbol)
      case Apply(Apply(id @ Ident(name), args1), args2) =>
        recordOwnerAnnotations(id.symbol)
        s"$name(${emitArgs(args1 ++ args2)})"
      case Apply(Apply(TypeApply(id @ Ident(name), _), args1), args2) =>
        recordOwnerAnnotations(id.symbol)
        s"$name(${emitArgs(args1 ++ args2)})"

      // `fn.apply(args)` on a Scala FunctionN → `fn(args)`. Scala renders
      // lambda invocation through `apply`; Dart calls a function value
      // directly with parentheses.
      case Apply(Select(qual, "apply"), args) if isFunctionType(qual.tpe) =>
        s"${emitExpr(qual)}(${emitArgs(args)})"
      case Apply(TypeApply(Select(qual, "apply"), _), args) if isFunctionType(qual.tpe) =>
        s"${emitExpr(qual)}(${emitArgs(args)})"

      // `throw expr` is lowered by Scala 3 to `Apply(Ident("throw"), args)`.
      // The Dart keyword `throw` is also a prefix-expression operator.
      // Positioned here (before the generic Apply catchall) so the
      // throw-shaped tree doesn't get eaten by the fallback.
      case Apply(id: Ident, List(arg)) if id.name == "throw" =>
        s"throw ${emitExpr(arg)}"
      case Apply(TypeApply(id: Ident, _), List(arg)) if id.name == "throw" =>
        s"throw ${emitExpr(arg)}"

      // Normal call: `obj.method(args)` or `Ident(method)(args)` for local calls.
      case Apply(sel @ Select(qual, name), args) =>
        recordAnnotations(qual.tpe.typeSymbol)
        emitMemberCall(qual, name, args, sel.symbol)
      // Generic method call: `obj.method[T](args)`. Same as above but with
      // an inner `TypeApply` that Scala types but Dart's type inference
      // handles on its own — so we drop the explicit type arguments.
      case Apply(TypeApply(sel @ Select(qual, name), _), args) =>
        recordAnnotations(qual.tpe.typeSymbol)
        emitMemberCall(qual, name, args, sel.symbol)
      case Apply(id: Ident, args) =>
        // Wildcard-imported members of facade objects arrive as bare
        // Idents — record the owning object's annotations so its
        // @DartImport / @DartPackage still reach the output.
        recordOwnerAnnotations(id.symbol)
        s"${dartSafeName(id.name)}(${emitArgs(args)})"
      case Apply(TypeApply(id: Ident, _), args) =>
        recordOwnerAnnotations(id.symbol)
        s"${dartSafeName(id.name)}(${emitArgs(args)})"
      case Apply(fn, args) =>
        s"${emitExpr(fn)}(${emitArgs(args)})"

      // Scala's unary operators (`!x`, `-x`, `~x`) compile to
      // `Select(x, "unary_!")` etc. Dart spells these as prefix forms, so
      // we can't route them through the generic member-access path.
      case Select(recv, "unary_!") =>
        val r = emitExpr(recv)
        if needsParensAsReceiver(recv) then s"!($r)" else s"!$r"
      case Select(recv, "unary_-") =>
        val r = emitExpr(recv)
        if needsParensAsReceiver(recv) then s"-($r)" else s"-$r"
      case Select(recv, "unary_~") =>
        val r = emitExpr(recv)
        if needsParensAsReceiver(recv) then s"~($r)" else s"~$r"
      case Select(recv, "unary_+") =>
        emitExpr(recv)

      // Field / method ref (no parens): `widget.title`, `Colors.deepPurple`.
      case Select(qual, name) =>
        recordAnnotations(qual.tpe.typeSymbol)
        recordAnnotations(t.tpe.typeSymbol)
        emitMemberAccess(qual, name)

      // Assignment as an expression (Dart allows this). Also handles the
      // case where a method body is a bare `x = y` — `emitBodyAsStatements`
      // routes non-Block terms through `emitExpr` via `emitTerminal`.
      case Assign(lhs, rhs) =>
        s"${emitExpr(lhs)} = ${emitExpr(rhs)}"

      // `if cond then t else e` → Dart ternary. Good enough when the if is
      // at expression position; statement-level if/else would want a block
      // shape, which we'll add when a fixture hits it.
      case If(cond, thenp, elsep) =>
        s"${emitExpr(cond)} ? ${emitExpr(thenp)} : ${emitExpr(elsep)}"

      // (Duplicate-throw case removed: the effective throw rewrite now
      // lives earlier in emitExpr, before the generic Apply catchall.)

      // `scrutinee match { case p => rhs; … }` → Dart 3 switch expression.
      // Emitted on a single line; `dart format` reformats to multi-line.
      // Pattern emission considers both the guard and the body when
      // deciding whether a bound name is "used".
      case Match(scrutinee, cases) =>
        val arms = cases.map { c =>
          val usageScope: Tree = c.guard match
            case Some(g) => Block(List(g), c.rhs)
            case None    => c.rhs
          val pat   = emitPattern(c.pattern, usageScope)
          val guard = c.guard.map(g => s" when ${emitExpr(g)}").getOrElse("")
          val rhs   = emitExpr(c.rhs)
          s"$pat$guard => $rhs"
        }.mkString(", ")
        s"switch (${emitExpr(scrutinee)}) { $arms }"

      case Typed(expr, _) =>
        emitExpr(expr)

      case Inlined(_, _, expansion) =>
        emitExpr(expansion)

      case other =>
        s"/* TODO expr ${other.getClass.getSimpleName} */"

    private def isNativeSingleton(t: Term): Boolean =
      val sym = t.tpe.termSymbol
      sym.exists && hasNative(sym)

    /** True when the term refers to an `@DartTopLevel`-marked facade
     *  object — its method calls emit without the object qualifier
     *  because the members are Dart top-level functions in reality.
     */
    private def isDartTopLevel(t: Term): Boolean =
      val sym = t match
        case id: Ident => id.symbol
        case s: Select => s.symbol
        case _         => Symbol.spliceOwner
      sym.exists && sym.annotations.exists(a => annoFqn(a) == "sart.dart.DartTopLevel")

    /** Names that are **getters** on common Dart types (String, List,
     *  Map, Set, int/double). Scala may compile a bare reference or a
     *  zero-arg call; Dart requires no parens.
     */
    private val dartGetterNames = Set(
      "isEmpty", "isNotEmpty", "length", "hashCode", "runtimeType",
      "first", "last", "single", "reversed", "keys", "values"
    )

    /** Names that are **methods** on common Dart types. Scala syntax
     *  often drops the parens for these; Dart requires them. Note that
     *  receiver type matters: `int.toDouble()` is a real Dart method,
     *  but `String.toInt`/`toDouble` need a wholly different translation
     *  (Dart's `String` has no `toInt` — use `int.parse(s)`). The
     *  rewrite table runs *before* this set in `emitMemberAccess`, so
     *  receiver-aware entries win where they apply.
     */
    private val dartMethodNamesNeedingParens = Set(
      "toList", "toSet", "toMap", "toString", "toInt", "toDouble",
      "trim", "toUpperCase", "toLowerCase", "clear", "dispose",
      "round", "abs", "floor", "ceil"
    )

    /** Does this term have an Option-like static type? Covers both the
     *  hand-ported `sart.stdlib.Option` and Scala's built-in `scala.Option`.
     */
    private def isOptionReceiver(t: Term): Boolean =
      val sym = t.tpe.typeSymbol
      sym.exists && (sym.fullName == "sart.stdlib.Option" || sym.fullName == "scala.Option")

    // ── Extension-call helpers ─────────────────────────────────────────

    private def extensionSym(fn: Term): Symbol = fn match
      case id: Ident       => id.symbol
      case s: Select       => s.symbol
      case TypeApply(f, _) => extensionSym(f)
      case _               => Symbol.spliceOwner

    private def isExtensionRef(fn: Term): Boolean =
      val sym = extensionSym(fn)
      sym.exists && sym.flags.is(Flags.ExtensionMethod)

    private def extensionCallName(fn: Term): String =
      dartSafeName(extensionSym(fn).name)

    // ── Option-match lowering ──────────────────────────────────────────

    /** Recognise a two-arm Option match: `case Some(v) => a` (binder or
     *  wildcard) plus `case None => b` / `case _ => b`, in either order.
     *  Returns (binderName, someRhs, noneRhs).
     */
    private def optionMatchArms(cases: List[CaseDef]): Option[(String, Term, Term)] =
      def someArm(c: CaseDef): Option[(String, Term)] = c.pattern match
        case Unapply(fun, _, List(sub)) if extensionSym(fun).fullName.startsWith("scala.Some")
            || extensionSym(fun).fullName.startsWith("sart.stdlib.Some") =>
          sub match
            case Bind(name, _) => Some((name, c.rhs))
            case _             => Some(("value_", c.rhs))
        case TypedOrTest(Unapply(fun, _, List(sub)), _) if extensionSym(fun).fullName.startsWith("scala.Some")
            || extensionSym(fun).fullName.startsWith("sart.stdlib.Some") =>
          sub match
            case Bind(name, _) => Some((name, c.rhs))
            case _             => Some(("value_", c.rhs))
        case _ => scala.None
      def noneArm(c: CaseDef): Option[Term] = c.pattern match
        case id: Ident if id.symbol.fullName == "scala.None" || id.symbol.fullName == "sart.stdlib.None" =>
          Some(c.rhs)
        case s: Select if s.symbol.fullName == "scala.None" || s.symbol.fullName == "sart.stdlib.None" =>
          Some(c.rhs)
        case Wildcard() => Some(c.rhs)
        case _          => scala.None
      if cases.length != 2 || cases.exists(_.guard.nonEmpty) then scala.None
      else
        (someArm(cases.head), cases.lift(1).flatMap(noneArm)) match
          case (Some((b, sr)), Some(nr)) => Some((b, sr, nr))
          case _ =>
            (cases.lift(1).flatMap(someArm), noneArm(cases.head)) match
              case (Some((b, sr)), Some(nr)) => Some((b, sr, nr))
              case _                         => scala.None

    // ── Async detection ────────────────────────────────────────────────

    /** A `= async { body }` wrapper — unwrapped so the body's statements
     *  emit directly inside an `async`-marked function (the declared
     *  Future[T] return stays; the body returns T values, like Dart).
     */
    private def unwrapAsync(t: Term): Option[Term] = t match
      case Apply(TypeApply(Select(q, "apply"), _), List(inner)) if isSartRef(q, "sart.dart.async") => Some(inner)
      case Apply(Select(q, "apply"), List(inner)) if isSartRef(q, "sart.dart.async") => Some(inner)
      case Inlined(_, _, e) => unwrapAsync(e)
      case Block(Nil, e)    => unwrapAsync(e)
      case _                => scala.None

    /** Does this tree contain an `await(...)` call OUTSIDE any nested
     *  closure/def? (An await inside a nested lambda makes THAT lambda
     *  async, not this one.)
     */
    private def containsAwait(tree: Tree): Boolean =
      val acc = new TreeAccumulator[Boolean]:
        def foldTree(found: Boolean, t: Tree)(owner: Symbol): Boolean =
          if found then true
          else t match
            case dd: DefDef => found // closure/def boundary — don't descend
            case Apply(TypeApply(Select(q, "apply"), _), _) if isSartRef(q, "sart.dart.await") => true
            case Apply(Select(q, "apply"), _) if isSartRef(q, "sart.dart.await") => true
            case _ => foldOverTree(found, t)(owner)
      acc.foldTree(false, tree)(Symbol.spliceOwner)

    /** Match a term that resolves to a specific fully-qualified Scala name,
     *  used for hand-ported stdlib special-cases (`sart.stdlib.Some`,
     *  `sart.stdlib.None`, etc.).
     */
    private def isSartRef(t: Term, fqn: String): Boolean =
      val sym = t match
        case id: Ident  => id.symbol
        case s: Select  => s.symbol
        case _          => Symbol.spliceOwner   // a dummy non-matching symbol
      sym.exists && sym.fullName == fqn

    /** Scala 3 inserts Predef-side implicit wrappers (`augmentString(s)`,
     *  `intWrapper(n)`, etc.) so `StringOps` / `RichInt` methods and
     *  operators are reachable on primitives. Dart's native `String`/`int`
     *  /`double` already provide those operators, so we strip the wrapper.
     *
     *  Matching by **simple name** rather than FQN because these methods
     *  are inherited through several `LowPriorityImplicits` parents and
     *  their FQN varies across Scala versions; the simple names are stable
     *  and unlikely to clash with user code.
     */
    private val scalaImplicitWrapperSimples = Set(
      "augmentString", "unaugmentString",
      "intWrapper", "longWrapper", "floatWrapper", "doubleWrapper",
      "charWrapper", "byteWrapper", "shortWrapper", "booleanWrapper",
      "wrapRefArray", "wrapIntArray", "wrapDoubleArray", "wrapLongArray",
      "wrapFloatArray", "wrapCharArray", "wrapByteArray", "wrapShortArray",
      "wrapBooleanArray", "wrapUnitArray", "genericWrapArray",
      "refArrayOps"
    )

    private def isScalaImplicitWrapper(t: Term): Boolean =
      val sym = t match
        case id: Ident           => id.symbol
        case s: Select           => s.symbol
        case TypeApply(inner, _) => inner match
          case id: Ident => id.symbol
          case s: Select => s.symbol
          case _         => Symbol.spliceOwner
        case _ => Symbol.spliceOwner
      sym.exists
        && scalaImplicitWrapperSimples(sym.name)
        && sym.fullName.startsWith("scala.")

    /** Produce the `"<qual>."` prefix for a member access, or `""` when the
     *  qualifier is `this` (Dart makes `this.` optional everywhere except a
     *  constructor initializer list, which we never emit via this path).
     *
     *  A more cautious version would preserve `this.` when a local variable
     *  in scope shadows the field; for the current subset we have no
     *  shadowing, so unconditional elision is safe.
     */
    private def selectPrefix(qual: Term): String = qual match
      case This(_) => ""
      case _       =>
        val s = emitExpr(qual)
        if needsParensAsReceiver(qual) then s"($s)." else s"$s."

    /** Trees whose emitted form binds looser than `.` in Dart — if they're
     *  used as the receiver of a `Select`/method call, we have to wrap them
     *  in parens so `(r * c).toString()` doesn't render as
     *  `r * c.toString()`.
     */
    private def needsParensAsReceiver(t: Term): Boolean = t match
      case Apply(Select(_, op), List(_)) if isBinaryOp(op) => true
      case If(_, _, _)                                     => true
      case Match(_, _)                                     => true
      case Assign(_, _)                                    => true
      // `x is Y` / `x as Y` bind looser than prefix `!` and `.`.
      case TypeApply(Select(_, "isInstanceOf"), _)         => true
      case TypeApply(Select(_, "asInstanceOf"), _)         => true
      // Wrappers are transparent in emission — look through them so a
      // wrapped ternary/binary still gets its parens.
      case Typed(e, _)                                     => needsParensAsReceiver(e)
      case Inlined(_, _, e)                                => needsParensAsReceiver(e)
      case Block(Nil, e: Term)                             => needsParensAsReceiver(e)
      case _                                               => false

    /** No-argument member access (`Select(qual, name)`). Consults the
     *  `StdlibRewrite` table for getter-style mappings (e.g. `xs.size` →
     *  `xs.length`, `xs.headOption` → `xs.isEmpty ? null : xs.first`),
     *  falling back to a direct `qual.name` emission.
     */
    /** Constructor-position type name: applied types keep their args
     *  (`GlobalKey<LoaderOverlayState>()` — a bare `GlobalKey()` would
     *  infer `GlobalKey<State<StatefulWidget>>`).
     */
    private def ctorTypeName(tpe: TypeRepr): String = tpe match
      case AppliedType(_, _) => emitTypeRef(tpe)
      case _                 => dartName(tpe.typeSymbol)

    private def emitMemberAccess(qual: Term, name: String): String =
      // @DartTopLevel facade field / constant → drop the qualifier so
      // `math.pi` emits as `pi` (or `alias.pi` for aliased imports).
      if isDartTopLevel(qual) then
        recordAnnotations(qual.tpe.termSymbol)
        return importAlias(qual.tpe.termSymbol).map(al => s"$al.$name").getOrElse(name)

      // `Dyn` bridge getters — casts and null checks on `dynamic`.
      if isDynReceiver(qual) then
        name match
          case "str"    => return s"(${emitExpr(qual)} as String)"
          case "toInt"  => return s"(${emitExpr(qual)} as int)"
          case "toBool" => return s"(${emitExpr(qual)} as bool)"
          case "isNull" => return s"(${emitExpr(qual)} == null)"
          case "toList" => return s"(${emitExpr(qual)} as List<dynamic>)"
          case _        => ()

      // Receiver-aware rewrites win first — they may translate to a
      // wholly different shape (e.g. `s.toInt` on a String receiver
      // becomes `int.parse(s)`, NOT `s.toInt()`). Falling back to the
      // generic paren-fix below would emit invalid Dart.
      stdlibRewrite(qual, name, isGetter = true) match
        case Some(rendered) => return rendered
        case None           => ()

      // Generic Scala-getter → Dart-method paren-fix for names whose
      // Dart counterpart is a method on most receivers (e.g.
      // `int.toDouble()`, `iter.toList()`). Never applies to members of
      // native facade *objects* (`Icons.clear` is an IconData getter, not
      // a call) — facades declare real methods with explicit parens.
      if dartMethodNamesNeedingParens(name) && !isNativeSingleton(qual) then
        return s"${selectPrefix(qual)}$name()"

      s"${selectPrefix(qual)}$name"

    /** Single place to render `qual.name(args…)` so Scala → Dart method
     *  name mappings land consistently regardless of which emitExpr entry
     *  point found the call. Consults the `StdlibRewrite` table for
     *  receiver-aware renames / polyfills.
     */
    private def emitMemberCall(qual: Term, name: String, args: List[Term], fnSym: Symbol = Symbol.noSymbol): String =
      // @DartTopLevel facade method → emit as a top-level Dart call
      // (no qualifier). This is how `math.sqrt(x)` lands as `sqrt(x)`.
      if isDartTopLevel(qual) then
        recordAnnotations(qual.tpe.termSymbol)
        val prefix = importAlias(qual.tpe.termSymbol).map(al => s"$al.").getOrElse("")
        return s"$prefix$name(${emitArgs(args)})"

      // Scala allows zero-arg method calls to be written without parens,
      // but also compiles `s.isEmpty` as `Apply(Select, Nil)` when
      // `isEmpty` has an empty parameter list. Dart is strict about
      // getter-vs-method, so no-arg calls to Dart *getters* must drop
      // the parens we'd otherwise emit.
      if args.isEmpty && dartGetterNames(name) then
        return emitMemberAccess(qual, name)

      // `Dyn` bridge: index access and getter-shaped calls on `dynamic`.
      if isDynReceiver(qual) then
        name match
          case "apply" => return s"${emitExpr(qual)}[${emitArgs(args)}]"
          case "str" | "toInt" | "toBool" | "isNull" | "toList" if args.isEmpty =>
            return emitMemberAccess(qual, name)
          case _ => ()

      // Index assignment on facade types: `x(k) = v` → `x[k] = v`. Scala
      // sugars this to `x.update(k, v)` — any @native-owned `update` with
      // exactly two args is Dart's `[]=` operator.
      if name == "update" && args.sizeIs == 2
         && fnSym.exists && hasNative(fnSym.owner) then
        return s"${emitExpr(qual)}[${emitExpr(args(0))}] = ${emitExpr(args(1))}"

      // Future companion constructors: Dart spells them differently.
      if isFutureCompanion(qual) then
        name match
          case "successful" => return s"Future.value(${emitArgs(args)})"
          case "failed"     => return s"Future.error(${emitArgs(args)})"
          case _            => ()

      // Case-class `.copy(x = v)` → the synthesised Dart `copyWith`, whose
      // params are all named. `copy`'s omitted args are `$default$` refs
      // (defaulting to the current field values) and get stripped.
      if fnSym.exists && name == "copy" && fnSym.owner.flags.is(Flags.Case) then
        val params = fnSym.paramSymss.flatten.filterNot(_.isType)
        val named = args.zipWithIndex.collect {
          case (arg, i) if !isDefaultArg(arg) =>
            val v = arg match
              case NamedArg(_, x) => x
              case o              => o
            s"${params(i).name}: ${emitExpr(v)}"
        }
        return s"${selectPrefix(qual)}copyWith(${named.mkString(", ")})"

      // Future.map/flatMap both map to Dart's `.then` — `.then` already
      // handles both the value-returning and Future-returning shapes via
      // its overloads, so we don't need the Scala distinction in Dart.
      // Drop the implicit ExecutionContext argument Scala inserts.
      val cleanedArgs =
        if isFutureReceiver(qual) then args.filterNot(isExecutionContextArg)
        else args
      // Render each arg the same way `emitArgs` does (NamedArg handling,
      // default-arg filtering) so rewrite templates see the same forms
      // whether they reach for `args` (joined) or `argList` (per-arg).
      val argList = cleanedArgs.filterNot(isDefaultArg).map {
        case NamedArg(name, value) => s"$name: ${emitExpr(value)}"
        case other                 => emitExpr(other)
      }
      val argStr = argList.mkString(", ")

      stdlibRewrite(qual, name, isGetter = false, argList, argStr) match
        case Some(rendered) => rendered
        case None =>
          // Calls to methods Sart itself emits must match the emitted
          // shape: named args for literal-defaulted params, positional
          // (name-stripped) for the rest.
          if isUserCallable(fnSym) then
            s"${selectPrefix(qual)}$name(${emitUserCallArgs(fnSym, cleanedArgs)})"
          else s"${selectPrefix(qual)}$name($argStr)"

    /** Lookup helper: walks `stdlibRewrites`, returning the first matching
     *  template's rendered output or `None`. Method-call entries receive
     *  both `argList` (one Dart expr per Scala argument) and `args` (the
     *  comma-joined form); getter-call entries get empty values.
     */
    private def stdlibRewrite(
      qual: Term, name: String, isGetter: Boolean,
      argList: List[String] = Nil, argStr: String = ""
    ): Option[String] =
      stdlibRewrites.find { e =>
        e.scalaName == name && e.isGetter == isGetter && e.receiver(qual)
      }.map { e =>
        val q = emitExpr(qual)
        e.emit(RewriteCtx(
          prefix   = selectPrefix(qual),
          // Parenthesize looser-binding receivers so templates that splice
          // `qualExpr` into `??`/`.`-chains keep the intended grouping.
          qualExpr = if needsParensAsReceiver(qual) then s"($q)" else q,
          args     = argStr,
          argList  = argList
        ))
      }

    /** A single Scala→Dart method-call rewrite. `prefix` is `qExpr.` (or
     *  empty when `qual` is `this`) — preserves the existing call-site
     *  elision behaviour. `qualExpr` is the bare expression for templates
     *  that need to reference it twice (e.g. `(q.isEmpty ? null : q.first)`).
     *  `argList` exposes pre-rendered individual args for templates that
     *  need to reorder or skip them (e.g. `Map.getOrElse(k, default)`).
     */
    private case class RewriteCtx(
      prefix:   String,
      qualExpr: String,
      args:     String,
      argList:  List[String]
    )

    private case class StdlibRewrite(
      receiver:  Term => Boolean,
      scalaName: String,
      isGetter:  Boolean,
      emit:      RewriteCtx => String
    )

    // Convenience constructors keep the table dense and readable.
    private def listGet(name: String, dartName: String) =
      StdlibRewrite(isListLikeReceiver, name, isGetter = true, c => s"${c.prefix}$dartName")

    private def listGetExpr(name: String)(template: String => String) =
      StdlibRewrite(isListLikeReceiver, name, isGetter = true, c => template(c.qualExpr))

    private def listCall(name: String)(template: RewriteCtx => String) =
      StdlibRewrite(isListLikeReceiver, name, isGetter = false, template)

    private def listRename(scalaName: String, dartName: String) =
      listCall(scalaName)(c => s"${c.prefix}$dartName(${c.args})")

    /** Scala→Dart method/getter mappings that depend on the receiver type.
     *  The order is irrelevant (predicates are mutually exclusive across
     *  types and `scalaName`+`isGetter` keys are unique within each type).
     *  Adding a new mapping is a one-line addition here.
     */
    private val stdlibRewrites: Seq[StdlibRewrite] = Seq(
      // ── List indexing: `xs(i)` → `xs[i]` ────────────────────────────
      listCall("apply")   (c => s"${c.prefix.stripSuffix(".")}[${c.args}]"),
      // ── List / Iterable getters ─────────────────────────────────────
      listGet("size",     "length"),
      listGet("head",     "first"),
      listGet("nonEmpty", "isNotEmpty"),
      // Templates that reference the qualifier multiple times.
      listGetExpr("init")      (q => s"$q.sublist(0, $q.length - 1)"),
      listGetExpr("tail")      (q => s"$q.sublist(1)"),
      listGetExpr("reverse")   (q => s"$q.reversed.toList()"),
      listGetExpr("headOption")(q => s"($q.isEmpty ? null : $q.first)"),
      listGetExpr("lastOption")(q => s"($q.isEmpty ? null : $q.last)"),

      // ── List / Iterable methods ─────────────────────────────────────
      // Materialising chain ops — Scala returns List, Dart returns
      // Iterable, so we force `.toList()` to keep the static type aligned.
      listCall("map")       (c => s"${c.prefix}map(${c.args}).toList()"),
      listCall("foreach")   (c => s"${c.prefix}forEach(${c.args})"),
      // Dart's List defines `+` as concatenation — the exact analogue.
      // Spread, not `+`: Dart's `List<E>.+` demands both sides share E,
      // but a spread literal computes the element LUB — matching Scala's
      // `++` unification (List[Text] ++ List[Card] → List[Widget]).
      listCall("++")        (c => s"[...(${c.prefix.stripSuffix(".")}), ...(${c.args})]"),
      listCall("concat")    (c => s"(${c.prefix.stripSuffix(".")} + ${c.args})"),
      listCall("filter")    (c => s"${c.prefix}where(${c.args}).toList()"),
      listCall("withFilter")(c => s"${c.prefix}where(${c.args}).toList()"),
      listCall("flatMap")   (c => s"${c.prefix}expand(${c.args}).toList()"),
      // Terminal scalars — no .toList() wrap.
      listCall("foldLeft")  (c => s"${c.prefix}fold(${c.args})"),
      listCall("mkString")  (c => s"${c.prefix}join(${c.args})"),
      // Direct renames where Dart's name differs from Scala's.
      listCall("drop")(c => s"${c.qualExpr}.skip(${c.args}).toList()"),
      listRename("dropWhile", "skipWhile"),
      listRename("exists",    "any"),
      listRename("forall",    "every"),
      // Same-name passthroughs that exist on Dart's Iterable.
      listCall("take")(c => s"${c.qualExpr}.take(${c.args}).toList()"),
      listRename("takeWhile", "takeWhile"),
      listRename("contains",  "contains"),
      listRename("indexOf",   "indexOf"),

      // ── Map ────────────────────────────────────────────────────────
      // Getters: `m.size`/`nonEmpty` rename; `keys`/`values` exist in Dart
      // unchanged but are listed explicitly so the table is the single
      // source of truth.
      StdlibRewrite(isMapReceiver, "size",     isGetter = true,  c => s"${c.prefix}length"),
      StdlibRewrite(isMapReceiver, "nonEmpty", isGetter = true,  c => s"${c.prefix}isNotEmpty"),
      StdlibRewrite(isMapReceiver, "keys",     isGetter = true,  c => s"${c.prefix}keys"),
      StdlibRewrite(isMapReceiver, "values",   isGetter = true,  c => s"${c.prefix}values"),
      // Methods.
      StdlibRewrite(isMapReceiver, "contains", isGetter = false,
        c => s"${c.prefix}containsKey(${c.args})"),
      // Scala's `m.get(k): Option[V]` matches Dart's `m[k]: V?` — Sart
      // models Option as a nullable, so the index form is exactly right.
      StdlibRewrite(isMapReceiver, "get", isGetter = false,
        c => s"${c.qualExpr}[${c.args}]"),
      // `m.getOrElse(k, default)` becomes `m[k] ?? default`.
      // `m ++ other` → Dart map-spread literal.
      StdlibRewrite(isMapReceiver, "++", isGetter = false,
        c => s"{...${c.qualExpr}, ...${c.argList(0)}}"),
      StdlibRewrite(isMapReceiver, "getOrElse", isGetter = false,
        c => s"(${c.qualExpr}[${c.argList(0)}] ?? ${c.argList(1)})"),

      // ── Option (nullable receiver via the sart_option.dart shim) ───
      // `o.orElse(alt)` → `(o ?? alt)`; both are nullable types.
      StdlibRewrite(isNullableOptionReceiver, "orElse", isGetter = false,
        c => s"(${c.qualExpr} ?? ${c.args})"),
      // `o.contains(x)` → `o == x` — works because Sart maps `Some(x)` to
      // a non-null value and `None` to `null`, so equality is exact.
      StdlibRewrite(isNullableOptionReceiver, "contains", isGetter = false,
        c => s"(${c.qualExpr} == ${c.args})"),
      // `o.exists(p)` → `o != null && p(o)` — guard then test.
      StdlibRewrite(isNullableOptionReceiver, "exists", isGetter = false,
        c => s"(${c.qualExpr} != null && (${c.args})(${c.qualExpr}!))"),
      // `o.forall(p)` → `o == null || p(o)` — vacuously true on absence.
      StdlibRewrite(isNullableOptionReceiver, "forall", isGetter = false,
        c => s"(${c.qualExpr} == null || (${c.args})(${c.qualExpr}!))"),
      // `o.filter(p)` → `o != null && p(o) ? o : null`.
      StdlibRewrite(isNullableOptionReceiver, "filter", isGetter = false,
        c => s"(${c.qualExpr} != null && (${c.args})(${c.qualExpr}!) ? ${c.qualExpr} : null)"),

      // ── Future ─────────────────────────────────────────────────────
      // `.map`/`.flatMap` collapse to Dart's overloaded `.then` — both
      // value- and Future-returning callbacks resolve through it.
      StdlibRewrite(isFutureReceiver, "map",     isGetter = false,
        c => s"${c.prefix}then(${c.args})"),
      StdlibRewrite(isFutureReceiver, "flatMap", isGetter = false,
        c => s"${c.prefix}then(${c.args})"),

      // ── Range construction (1 to 10 / 1 until 10) ──────────────────
      // Receiver is an Int (or Predef-wrapped RichInt — the wrapper
      // itself is stripped earlier in emitExpr). Materialise as a Dart
      // List<int>; if the user chains .map / .where / .toList / .foreach
      // on it, those resolve through the existing list-like rewrites
      // because Scala's Range type starts with `scala.collection.`.
      // Qualifier evaluated twice — fine for literal ints, less ideal
      // for expressions; matches the existing zip / partition trade-off.
      StdlibRewrite(isIntReceiver, "to",    isGetter = false,
        c => s"List<int>.generate(${c.argList(0)} - ${c.qualExpr} + 1, (i) => ${c.qualExpr} + i)"),
      StdlibRewrite(isIntReceiver, "until", isGetter = false,
        c => s"List<int>.generate(${c.argList(0)} - ${c.qualExpr}, (i) => ${c.qualExpr} + i)"),

      // ── Tuple field access ─────────────────────────────────────────
      // `t._N` → Dart record positional getter `t.$N`. Cover up through
      // _9 — covers all common cases; Scala supports up to _22 on the
      // legacy TupleN classes.
      StdlibRewrite(isTupleReceiver, "_1", isGetter = true, c => s"${c.prefix}$$1"),
      StdlibRewrite(isTupleReceiver, "_2", isGetter = true, c => s"${c.prefix}$$2"),
      StdlibRewrite(isTupleReceiver, "_3", isGetter = true, c => s"${c.prefix}$$3"),
      StdlibRewrite(isTupleReceiver, "_4", isGetter = true, c => s"${c.prefix}$$4"),
      StdlibRewrite(isTupleReceiver, "_5", isGetter = true, c => s"${c.prefix}$$5"),
      StdlibRewrite(isTupleReceiver, "_6", isGetter = true, c => s"${c.prefix}$$6"),
      StdlibRewrite(isTupleReceiver, "_7", isGetter = true, c => s"${c.prefix}$$7"),
      StdlibRewrite(isTupleReceiver, "_8", isGetter = true, c => s"${c.prefix}$$8"),
      StdlibRewrite(isTupleReceiver, "_9", isGetter = true, c => s"${c.prefix}$$9"),

      // ── Set ────────────────────────────────────────────────────────
      // Carved out of `isListLikeReceiver` so chain ops don't get
      // wrongly forced through `.toList()`. Most ops pass through
      // unchanged on Dart's Set; only the renames need entries.
      StdlibRewrite(isSetReceiver, "size",     isGetter = true,
        c => s"${c.prefix}length"),
      StdlibRewrite(isSetReceiver, "nonEmpty", isGetter = true,
        c => s"${c.prefix}isNotEmpty"),

      // ── List/Iterable: nullable-returning lookups ──────────────────
      // Scala's `List.find(p): Option[T]` ↔ Sart's nullable Option.
      // Avoid Dart's `firstWhere(orElse: ...)` because non-null T
      // disallows `() => null` — instead, materialise the matches and
      // pick the first or null. Slightly more allocation but uniform
      // across element nullability.
      listCall("find") (c => s"((){ final r = ${c.qualExpr}.where(${c.args}).toList(); return r.isEmpty ? null : r.first; })()"),
      // `xs.count(p)` → `xs.where(p).length`.
      listCall("count")(c => s"${c.qualExpr}.where(${c.args}).length"),

      // ── List/Iterable: structural ops ──────────────────────────────
      // `xss.flatten` → `xss.expand((x) => x).toList()`.
      // TASTy preserves the `implicit ev: A => IterableOnce[B]` as an
      // explicit arg, so cover both the getter and method shapes; the
      // method form ignores args entirely.
      listGetExpr("flatten")(q => s"$q.expand((x) => x).toList()"),
      listCall("flatten")(c => s"${c.qualExpr}.expand((x) => x).toList()"),
      // `xs.distinct` — go through Set to dedupe; Dart's Set preserves
      // insertion order, matching Scala's `distinct` semantics.
      listGetExpr("distinct")(q => s"$q.toSet().toList()"),
      // `xs.sorted` — Dart's `sort()` mutates in place; cascade syntax
      // returns the materialised receiver. The Scala variant takes an
      // implicit Ordering; we ignore it and rely on Dart's Comparable.
      // Caught here as a getter-style entry; fall-through table also
      // covers the `Apply(Select, List(implicitOrd))` shape if TASTy
      // preserves the implicit as an explicit arg.
      listGetExpr("sorted")(q => s"($q.toList()..sort())"),
      listCall("sorted")(c => s"(${c.qualExpr}.toList()..sort())"),
      // `xs.sortBy(f)` — sort by extracted key. `f` may get called twice
      // per comparison; acceptable for MVP. Implicit Ordering ignored.
      listCall("sortBy")(c =>
        s"(${c.qualExpr}.toList()..sort((a, b) => Comparable.compare(" +
        s"(${c.argList(0)})(a) as Comparable, (${c.argList(0)})(b) as Comparable)))"),
      // `xs.foldRight(z)(op)` — reverse the list, then foldLeft with
      // swapped lambda args (`op` expects `(A, B)`, Dart's fold passes
      // `(acc, elem)`).
      listCall("foldRight")(c =>
        s"${c.qualExpr}.reversed.fold(${c.argList(0)}, (acc, a) => (${c.argList(1)})(a, acc))"),

      // ── List/Iterable: pairing ops (require Tuple support) ────────
      // `xs.zip(ys)` → `List<(A, B)>`. Dart has no built-in zip; build
      // pairs by index up to the shorter length. Args are referenced
      // multiple times — acceptable for typical identifier args, and
      // matches the existing partition / sortBy idiom in this table.
      listCall("zip")(c =>
        s"List.generate((${c.qualExpr}.length < ${c.argList(0)}.length ? " +
        s"${c.qualExpr}.length : ${c.argList(0)}.length), " +
        s"(i) => (${c.qualExpr}[i], ${c.argList(0)}[i]))"),
      // `xs.zipWithIndex` → `List<(A, Int)>`. Note Scala puts the index
      // SECOND in each pair (Dart's `Iterable.indexed` puts it first),
      // so we hand-build pairs in Scala's order.
      listGetExpr("zipWithIndex")(q =>
        s"List.generate($q.length, (i) => ($q[i], i))"),
      listCall("zipWithIndex")(c =>
        s"List.generate(${c.qualExpr}.length, (i) => (${c.qualExpr}[i], i))"),
      // `xs.partition(p)` → `(matching, not-matching)`. Calls p twice
      // per element; acceptable for MVP.
      listCall("partition")(c =>
        s"(${c.qualExpr}.where(${c.argList(0)}).toList(), " +
        s"${c.qualExpr}.where((x) => !(${c.argList(0)})(x)).toList())"),

      // ── Map mutators (return new Map) ─────────────────────────────
      // `m.updated(k, v)` → `{...m, k: v}` (Dart spread on map literal).
      StdlibRewrite(isMapReceiver, "updated", isGetter = false,
        c => s"{...${c.qualExpr}, ${c.argList(0)}: ${c.argList(1)}}"),

      // ── List/Iterable: numeric reductions ─────────────────────────
      // Each takes an implicit Numeric/Ordering in TASTy that we ignore.
      // `sum` and `product` start from a literal zero/one — correct for
      // `List[Int]` and `List[Long]`. `List[Double]` users may need to
      // cast the result from `num` to `double`, or fold directly with
      // a `0.0` seed; deliberate trade-off for table simplicity.
      // `min`/`max` use `reduce`, which (matching Scala) throws on an
      // empty list rather than requiring a seed.
      // Both getter (Scala syntax) and method (TASTy with implicit) shapes.
      listGetExpr("sum")    (q => s"$q.fold(0, (a, b) => a + b)"),
      listCall("sum")        (c => s"${c.qualExpr}.fold(0, (a, b) => a + b)"),
      listGetExpr("product")(q => s"$q.fold(1, (a, b) => a * b)"),
      listCall("product")    (c => s"${c.qualExpr}.fold(1, (a, b) => a * b)"),
      listGetExpr("min")    (q => s"$q.reduce((a, b) => a < b ? a : b)"),
      listCall("min")        (c => s"${c.qualExpr}.reduce((a, b) => a < b ? a : b)"),
      listGetExpr("max")    (q => s"$q.reduce((a, b) => a > b ? a : b)"),
      listCall("max")        (c => s"${c.qualExpr}.reduce((a, b) => a > b ? a : b)"),

      // ── String ─────────────────────────────────────────────────────
      // All three are parameterless Scala `def`s (callable without
      // parens), so they reach `emitMemberAccess` — `isGetter = true`.
      // `s.toInt` / `s.toDouble` parse via Dart's static factories
      // (Dart's `String` has no `toInt`); `int.parse` throws on bad
      // input, matching Scala's `NumberFormatException` semantics.
      StdlibRewrite(isStringReceiver, "toInt", isGetter = true,
        c => s"int.parse(${c.qualExpr})"),
      StdlibRewrite(isStringReceiver, "toDouble", isGetter = true,
        c => s"double.parse(${c.qualExpr})"),
      // Java's `String.replace` (all occurrences, literal match) is
      // Dart's `replaceAll`.
      StdlibRewrite(isStringReceiver, "replace", isGetter = false,
        c => s"${c.qualExpr}.replaceAll(${c.argList(0)}, ${c.argList(1)})"),
      // tryParse returns null on failure — exactly Option's Dart shape.
      StdlibRewrite(isStringReceiver, "toIntOption", isGetter = true,
        c => s"int.tryParse(${c.qualExpr})"),
      StdlibRewrite(isStringReceiver, "toDoubleOption", isGetter = true,
        c => s"double.tryParse(${c.qualExpr})"),
      // Scala's `capitalize` — Dart has no equivalent; inline ternary.
      StdlibRewrite(isStringReceiver, "capitalize", isGetter = true,
        c => s"(${c.qualExpr}.isEmpty ? ${c.qualExpr} : ${c.qualExpr}[0].toUpperCase() + ${c.qualExpr}.substring(1))"),
      // Scala's `stripMargin` strips leading whitespace + `|` per line.
      // Mirror with a Dart regex: every match of `^\s*\|` becomes ''.
      StdlibRewrite(isStringReceiver, "stripMargin", isGetter = true,
        c => s"${c.qualExpr}.replaceAll(RegExp(r'^\\s*\\|', multiLine: true), '')")
    )

    /** True when `t` has a Scala `List`-style static type — we rewrite its
     *  chain methods to their Dart Iterable equivalents and append
     *  `.toList()`. Keep the check narrow (FQN starts with
     *  `scala.collection.`) so user-defined types named "List" aren't
     *  accidentally caught.
     */
    private def isListLikeReceiver(t: Term): Boolean =
      val sym = t.tpe.typeSymbol
      sym.exists && sym.fullName.startsWith("scala.collection.") &&
        !isMapReceiver(t) && !isSetReceiver(t)

    private def isUnitTyped(t: Term): Boolean =
      t.tpe.typeSymbol.fullName == "scala.Unit"

    /** Trees that only have a statement rendering in Dart — a trailing
     *  one must NOT be routed through the expression/temp-val-inline
     *  path (a Unit `if` becomes a void ternary; a `try`/`while` has no
     *  expression form at all).
     */
    private def isStatementOnlyTerm(t: Term): Boolean = t match
      case Typed(e, _)      => isStatementOnlyTerm(e)
      case Inlined(_, _, e) => isStatementOnlyTerm(e)
      case i @ If(_, _, _)  => isUnitTyped(i)
      case m @ Match(_, _)  => isUnitTyped(m)
      case _: Try           => isUnitTyped(t)
      case _: While         => true
      case _                => false

    /** Record the annotations of a bare Ident's owning facade object (and
     *  its companions) — no-op for non-facade owners.
     */
    private def recordOwnerAnnotations(sym: Symbol): Unit =
      if sym.exists then
        val owner = sym.owner
        if owner.exists then
          recordAnnotations(owner)
          val mv = owner.companionModule
          if mv.exists then recordAnnotations(mv)

    /** True when `t`'s static type is Sart's `Dyn` (Dart `dynamic`). */
    private def isDynReceiver(t: Term): Boolean =
      val sym = t.tpe.typeSymbol
      sym.exists && sym.fullName == "sart.dart.Dyn"

    /** True when `t` is the `scala.concurrent.Future` companion object. */
    private def isFutureCompanion(t: Term): Boolean =
      val sym = t.tpe.termSymbol
      sym.exists && sym.fullName == "scala.concurrent.Future"

    /** True when `t`'s static type is `scala.concurrent.Future[...]`. */
    private def isFutureReceiver(t: Term): Boolean =
      val sym = t.tpe.typeSymbol
      sym.exists && sym.fullName == "scala.concurrent.Future"

    /** True when `t`'s static type is a Scala `Map`. Matches the common
     *  immutable / mutable / root variants.
     */
    private def isMapReceiver(t: Term): Boolean =
      val fq = t.tpe.typeSymbol.fullName
      fq == "scala.collection.immutable.Map" ||
      fq == "scala.collection.mutable.Map"   ||
      fq == "scala.collection.Map"

    /** True when `t`'s static type is one of the Option flavours Sart
     *  models as Dart nullables (`scala.Option` or `sart.stdlib.Option`).
     *  Used by the rewrite table to attach Option-specific method
     *  polyfills (orElse, contains, exists, forall, filter) on top of the
     *  ones already covered by the sart_option.dart shim (map/flatMap/
     *  fold/foreach).
     */
    private def isNullableOptionReceiver(t: Term): Boolean =
      val fq = t.tpe.typeSymbol.fullName
      fq == "scala.Option" || fq == "sart.stdlib.Option"

    /** True when `t`'s static type is `String` (java.lang.String or
     *  the Predef alias). Lets the rewrite table attach String-specific
     *  rewrites like `.toInt` / `.toDouble` / `.stripMargin`.
     */
    private def isStringReceiver(t: Term): Boolean = isStringType(t.tpe)

    /** True when `t`'s static type is a Scala `Set`. Pulled out of the
     *  list-like umbrella so Set-specific rewrites (`size` → `length`)
     *  don't get double-translated and so chain ops on Sets aren't
     *  forced to materialise as `.toList()`.
     */
    private def isSetReceiver(t: Term): Boolean =
      val fq = t.tpe.typeSymbol.fullName
      fq == "scala.collection.immutable.Set" ||
      fq == "scala.collection.mutable.Set"   ||
      fq == "scala.collection.Set"

    /** True when `t`'s static type is `scala.TupleN` for any N. Lets the
     *  rewrite table translate `t._1`/`._2`/… into Dart's record-getter
     *  syntax `t.$1`/`.$2`/….
     */
    private def isTupleReceiver(t: Term): Boolean =
      t.tpe.typeSymbol.fullName.matches("scala\\.Tuple\\d+")

    /** True when `t`'s static type is `Int`/`Long` (or its Predef wrapper
     *  `RichInt`/`RichLong`). Lets the rewrite table catch `1 to 10`
     *  patterns where the receiver is the int literal under
     *  Predef.intWrapper. The wrapper itself gets stripped at emit time.
     */
    private def isIntReceiver(t: Term): Boolean =
      val fq = t.tpe.typeSymbol.fullName
      fq == "scala.Int" || fq == "scala.Long" ||
      fq == "scala.runtime.RichInt" || fq == "scala.runtime.RichLong"

    /** True when `t` references the companion object of a case class
     *  (i.e. `Ref(Todo)` where `class Todo` is a case class). Detects
     *  the `Foo.apply(...)` → `Foo(...)` rewrite site.
     */
    private def isCaseClassCompanion(t: Term): Boolean =
      val sym = t match
        case id: Ident => id.symbol
        case s: Select => s.symbol
        case _         => Symbol.spliceOwner
      sym.exists && sym.flags.is(Flags.Module) && {
        val companion = sym.companionClass
        companion.exists && companion.flags.is(Flags.Case)
      }

    /** Dart class name for a case-class companion reference — strips the
     *  `$` suffix Scala adds to module names if any, honouring `@DartName`.
     */
    private def caseClassNameFor(t: Term): String =
      val sym = t match
        case id: Ident => id.symbol
        case s: Select => s.symbol
        case _         => Symbol.spliceOwner
      val companion = sym.companionClass
      if companion.exists then dartName(companion) else sym.name.stripSuffix("$")

    /** Primary-constructor symbol of the case class behind a companion
     *  reference — for shaping `Foo(args)` companion-apply call sites.
     */
    private def companionClassCtor(t: Term): Symbol =
      val sym = t match
        case id: Ident => id.symbol
        case s: Select => s.symbol
        case _         => Symbol.spliceOwner
      val companion = sym.companionClass
      if companion.exists then companion.primaryConstructor else Symbol.noSymbol

    /** Recognise Scala's implicit `ExecutionContext` argument so we can
     *  drop it when emitting a Dart Future call — Dart has no EC concept.
     */
    private def isExecutionContextArg(t: Term): Boolean =
      val fq = t.tpe.typeSymbol.fullName
      fq == "scala.concurrent.ExecutionContext" || fq == "scala.concurrent.ExecutionContextExecutor"

    private def isBinaryOp(op: String): Boolean =
      Set("+", "-", "*", "/", "%", "==", "!=", "<", ">", "<=", ">=", "&&", "||").contains(op)

    private def isStringType(tpe: TypeRepr): Boolean =
      // `widen` first: a bare parameter/val receiver types as a TermRef
      // singleton, whose `typeSymbol` is NOT the underlying class.
      val fq = tpe.widen.dealias.typeSymbol.fullName
      fq == "java.lang.String" || fq == "scala.Predef.String" ||
      // `s.toInt` etc. flow through Predef's `augmentString` implicit
      // wrapper, which gives the receiver type `StringOps` even though
      // the user wrote a plain `String`. Treat the wrapped form as a
      // String so the rewrite table recognises it.
      fq == "scala.collection.StringOps"

    private def isFunctionType(tpe: TypeRepr): Boolean =
      tpe.typeSymbol.fullName.matches("scala\\.Function\\d+")

    /** Extract the items of a Scala varargs argument. Matches both the
     *  `Typed(Repeated(items, _), _)` shape (most common) and a bare
     *  `Repeated(items, _)` that sometimes appears.
     */
    private def varargsItems(t: Term): List[Term] = t match
      case Typed(Repeated(items, _), _) => items
      case Repeated(items, _)           => items
      case _                            => Nil

    /** True when `t` is syntactically a varargs wrapper (Repeated/Typed-
     *  Repeated), even if the enclosed item list is empty. Used as a
     *  guard on literal-collection patterns so `List()` still matches
     *  the List-literal rewrite and produces `[]` rather than a generic
     *  `List.apply()` call.
     */
    private def isVarargs(t: Term): Boolean = t match
      case Typed(Repeated(_, _), _) => true
      case Repeated(_, _)           => true
      case _                        => false

    /** Extract a `"k" -> v` Scala entry as a `"k: v"` Dart map-literal
     *  fragment. Returns `None` for shapes we don't recognise so the
     *  caller can substitute a TODO / omit.
     */
    private def mapEntry(t: Term): Option[String] = t match
      // Predef.ArrowAssoc(k).->(v)
      case Apply(Select(Apply(_, List(key)), "->"), List(value)) =>
        Some(s"${emitExpr(key)}: ${emitExpr(value)}")
      case Apply(TypeApply(Select(Apply(_, List(key)), "->"), _), List(value)) =>
        Some(s"${emitExpr(key)}: ${emitExpr(value)}")
      case Apply(Select(Apply(TypeApply(_, _), List(key)), "->"), List(value)) =>
        Some(s"${emitExpr(key)}: ${emitExpr(value)}")
      case _ =>
        None

    /** Drop references to Scala's synthesised default-argument methods
     *  (e.g. `Text.$lessinit$greater$default$2`). Dart named args with
     *  defaults simply go unmentioned at the call site.
     */
    private def isDefaultArg(t: Term): Boolean = t match
      case s: Select if s.name.contains("$default$") => true
      case Ident(n) if n.contains("$default$") => true
      case Apply(inner, _) => isDefaultArg(inner)
      case TypeApply(inner, _) => isDefaultArg(inner)
      case NamedArg(_, inner) => isDefaultArg(inner)
      case _ => false

    // ── Named/default parameters for user-defined callables ─────────────

    /** The Dart-side parameter shape of a user callable: positional params
     *  first, then a named section for every param whose Scala default is
     *  a literal we can carry over as a Dart default value. Params with
     *  non-literal defaults stay positional-required (loud at analyze
     *  time if omitted) until default-getter emission lands.
     */
    private case class DartParamShape(positional: List[ValDef], named: List[(ValDef, String)])

    private def dartParamShape(callable: Symbol, params: List[ValDef], idxOffset: Int = 0): DartParamShape =
      val pos   = List.newBuilder[ValDef]
      val named = List.newBuilder[(ValDef, String)]
      params.zipWithIndex.foreach { case (p, i) =>
        val dflt =
          if p.symbol.flags.is(Flags.HasDefault) then literalDefaultFor(callable, idxOffset + i + 1)
          else None
        dflt match
          case Some(d) => named += ((p, d))
          case None    => pos += p
      }
      DartParamShape(pos.result(), named.result())

    /** Emitted Dart literal for the `idx`-th (1-based) default of
     *  `callable`, if that default is a plain literal. Scala stores
     *  defaults in synthesised getters (`f$default$2` on the owner;
     *  `$lessinit$greater$default$2` on the companion for constructors).
     */
    private def literalDefaultFor(callable: Symbol, idx: Int): Option[String] =
      try
        val (owner, base) =
          if callable.isClassConstructor then
            (callable.owner.companionModule, "$lessinit$greater")
          else (callable.owner, callable.name)
        if !owner.exists then return None
        val getterName = s"$base$$default$$$idx"
        val getter = owner.methodMember(getterName).headOption.orElse {
          val mc = owner.moduleClass
          if mc.exists then mc.methodMember(getterName).headOption else None
        }
        def unwrapT(t: Term): Term = t match
          case Inlined(_, _, e) => unwrapT(e)
          case Typed(e, _)      => unwrapT(e)
          case other            => other
        getter.flatMap { g =>
          g.tree match
            case dd: DefDef =>
              dd.rhs.map(unwrapT).flatMap {
                case Literal(c) => Some(emitConstant(c))
                // `= None` (Option default) — a `null` literal in Dart, so
                // the param stays named-with-default instead of positional.
                case t: Term if isSartRef(t, "scala.None") || isSartRef(t, "sart.stdlib.None") =>
                  Some("null")
                // `= Colors.red` / `= TextAlign.start` — a facade static
                // reference; Dart-side these are consts, so they survive
                // as named-param defaults.
                case t @ Select(_, _) if t.symbol.exists && t.symbol.owner.exists
                    && hasNative(t.symbol.owner) =>
                  Some(emitExpr(t))
                case _ => None
              }
            case _ => None
        }
      catch case _: Throwable => None

    /** A callable whose declaration Sart itself emits (so call sites must
     *  match the emitted positional/named shape) — i.e. not a facade and
     *  not part of the Scala/Java stdlib.
     */
    private def isUserCallable(sym: Symbol): Boolean =
      sym.exists && {
        val owner = sym.owner
        owner.exists && !hasNative(owner) &&
          !sym.fullName.startsWith("scala.") &&
          !sym.fullName.startsWith("java.")
      }

    /** Render call args against a user callable's emitted shape: args for
     *  literal-defaulted params become `name: value` (and Dart requires
     *  named args after positional ones, so they're moved last); omitted
     *  defaults are stripped — the Dart-side default takes over.
     */
    private def emitUserCallArgs(callable: Symbol, args: List[Term], dropParams: Int = 0): String =
      val params = callable.paramSymss.flatten.filterNot(_.isType).drop(dropParams)
      val pos    = List.newBuilder[String]
      val named  = List.newBuilder[String]
      args.zipWithIndex.foreach { case (arg, i) =>
        if !isDefaultArg(arg) then
          val pOpt  = params.lift(i)
          val inner = arg match
            case NamedArg(_, v) => v
            case other          => other
          val isNamed = pOpt.exists(p =>
            p.flags.is(Flags.HasDefault) && literalDefaultFor(callable, dropParams + i + 1).isDefined)
          if isNamed then named += s"${pOpt.get.name}: ${emitExpr(inner)}"
          else pos += emitExpr(inner)
      }
      (pos.result() ++ named.result()).mkString(", ")

    private def emitArgs(args: List[Term]): String =
      args.filterNot(isDefaultArg).map {
        case NamedArg(name, value) => s"$name: ${emitExpr(value)}"
        case other => emitExpr(other)
      }.mkString(", ")

    /** Variant of `emitArgs` that drops any `NamedArg` wrapper, emitting
     *  every argument positionally. Used when the target has a positional
     *  Dart constructor (user classes) but the Scala source passed values
     *  using named-argument syntax.
     */
    private def emitPositionalArgs(args: List[Term]): String =
      args.filterNot(isDefaultArg).map {
        case NamedArg(_, value) => emitExpr(value)
        case other              => emitExpr(other)
      }.mkString(", ")

    private def emitConstant(c: Constant): String = c.value match
      case s: String  => "'" + escapeDartString(s) + "'"
      case b: Boolean => b.toString
      case n: Int     => n.toString
      case n: Long    => n.toString
      case n: Double  => n.toString
      case n: Float   => n.toString
      case ()         => "null"
      case null       => "null"
      case other      => s"/* TODO const $other */"

    private def escapeDartString(s: String): String =
      s.flatMap {
        case '\\' => "\\\\"
        case '\'' => "\\'"
        case '\n' => "\\n"
        case '\r' => "\\r"
        case '\t' => "\\t"
        case '$'  => "\\$"
        case c    => c.toString
      }

    /** Translate a Scala match-pattern tree to a Dart 3 pattern arm.
     *  Drops the binding name when the case body doesn't reference it,
     *  so Dart's unused-variable lint stays quiet.
     */
    private def emitPattern(p: Tree, body: Tree): String = p match
      case Literal(c)                        => emitConstant(c)
      case Ident("_")                        => "_"
      // Scala 3 emits `Wildcard()` for `_` inside Unapply sub-patterns
      // (distinct from `Ident("_")` in the outer pattern form).
      case w: Wildcard                       => "_"
      case Bind(name, Wildcard())            =>
        if bodyUsesIdent(body, name) then s"var $name" else "_"
      case Bind(name, Ident("_")) =>
        if bodyUsesIdent(body, name) then s"var $name" else "_"
      case Typed(Ident("_"), tpt)            => s"${emitTypeRef(tpt.tpe)} _"
      case Bind(name, Typed(Ident("_"), tpt)) =>
        val t = emitTypeRef(tpt.tpe)
        if bodyUsesIdent(body, name) then s"$t $name" else s"$t _"

      // Constructor patterns — `case Foo(a, b)` / `case Success(v)`.
      // Dart 3 object patterns spell this `Foo(field: subpattern, …)` by
      // field name, not by position. So we look up the case class's
      // caseFields (which are in declaration order) and pair them with
      // the Scala pattern subtrees.
      case u: Unapply =>
        emitUnapplyPattern(u, body, explicitType = None)
      // A `Typed(Unapply(…), tpt)` OR Scala 3's `TypedOrTest(Unapply(…),
      // tpt)` — both come up when pattern-matching a subtype of a
      // sealed hierarchy (e.g. `case Success(v)` on a `Try[Int]`). Carry
      // the type as the Dart pattern prefix.
      case Typed(u: Unapply, tpt) =>
        emitUnapplyPattern(u, body, explicitType = Some(tpt.tpe))
      case TypedOrTest(u: Unapply, tpt) =>
        emitUnapplyPattern(u, body, explicitType = Some(tpt.tpe))

      case s: Select => emitExpr(s)
      case Ident(n)  => n
      case _         => s"/* TODO pattern ${p.getClass.getSimpleName} */"

    /** Render a Scala `Unapply(fun, _, subPatterns)` as a Dart object
     *  pattern. Uses the case-class's declared field names to label the
     *  subpatterns, since Dart 3 object patterns are name-based.
     */
    private def emitUnapplyPattern(u: Unapply, body: Tree, explicitType: Option[TypeRepr]): String =
      val ctorSym = ctorSymFor(u.fun)
      val fieldNames: List[String] = ctorSym.flatMap(caseFieldNames).getOrElse(Nil)
      val typeName =
        explicitType.map(emitTypeRef)
          .orElse(ctorSym.map(dartName))
          .getOrElse("_")
      val argStrs: List[String] = u.patterns.zipWithIndex.map { case (subPat, idx) =>
        val field = fieldNames.lift(idx).getOrElse("")
        val rendered = emitPattern(subPat, body)
        if field.isEmpty then rendered else s"$field: $rendered"
      }
      s"$typeName(${argStrs.mkString(", ")})"

    /** Extract the case class's companion-class symbol from an Unapply's
     *  `fun`, whatever wrapper shape it arrived in.
     */
    private def ctorSymFor(fun: Term): Option[Symbol] =
      val sym = fun match
        case TypeApply(Select(id: Ident, "unapply"), _) => id.symbol
        case Select(id: Ident, "unapply")               => id.symbol
        case TypeApply(Select(sel: Select, "unapply"), _) => sel.symbol
        case Select(sel: Select, "unapply")             => sel.symbol
        case _ => Symbol.spliceOwner
      val companion = if sym.exists then sym.companionClass else Symbol.spliceOwner
      if companion.exists then Some(companion) else None

    /** Primary-ctor parameter names in declaration order — the Scala case
     *  class's `unapply` decomposes by position, and these names are how
     *  we surface each position to Dart's named-field pattern syntax.
     */
    private def caseFieldNames(classSym: Symbol): Option[List[String]] =
      val ctor = classSym.primaryConstructor
      if !ctor.exists then return None
      ctor.tree match
        case dd: DefDef =>
          Some(dd.paramss.flatMap(_.params).collect { case vd: ValDef => vd.name })
        case _ => None

    /** Scan `tree` for any `Ident(name)` reference. Used to decide whether
     *  a pattern's Bind needs to carry its name over or can become `_`.
     */
    private def bodyUsesIdent(tree: Tree, name: String): Boolean =
      var found = false
      object Finder extends TreeTraverser:
        override def traverseTree(t: Tree)(owner: Symbol): Unit =
          if !found then t match
            case Ident(n) if n == name => found = true
            case _ => super.traverseTree(t)(owner)
      Finder.traverseTree(tree)(Symbol.spliceOwner)
      found

    /** Strip `Inlined(...)` wrappers the compiler sometimes adds. */
    private def unwrap(t: Term): Term = t match
      case Inlined(_, _, e) => unwrap(e)
      case _ => t

    private def isStringContextRef(t: Term): Boolean = unwrap(t) match
      case Ident("StringContext") => true
      case Select(_, "StringContext") => true
      case _ => false

    /** Attempt to recognise a `StringContext(parts...)` construction at any
     *  of the shapes the compiler may produce and return the constant string
     *  parts. Empty list means "not a StringContext construction."
     */
    private def stringContextParts(t: Term): List[String] =
      unwrap(t) match
        case Apply(Select(ref, "apply"), argList) if isStringContextRef(ref) =>
          val partsTerms = argList match
            case List(Typed(Repeated(ps, _), _)) => ps
            case List(Repeated(ps, _))           => ps
            case ps                              => ps
          partsTerms.flatMap(p => litValue(p).collect { case s: String => s })
        case Apply(TypeApply(Select(ref, "apply"), _), argList) if isStringContextRef(ref) =>
          val partsTerms = argList match
            case List(Typed(Repeated(ps, _), _)) => ps
            case List(Repeated(ps, _))           => ps
            case ps                              => ps
          partsTerms.flatMap(p => litValue(p).collect { case s: String => s })
        case _ => Nil

    /** Render `'prefix $x middle ${expr} suffix'` given the string parts and
     *  the interpolation argument expressions.
     */
    private def emitInterpolationParts(parts: List[String], args: List[Term]): String =
      val b = new StringBuilder("'")
      val partsIter = parts.iterator
      val argsIter  = args.iterator
      if partsIter.hasNext then b.append(escapeDartString(partsIter.next()))
      while argsIter.hasNext do
        val a = argsIter.next()
        a match
          // Braced (`${n}`) so temp-val inlining can substitute an
          // expression in place of the name without corrupting the string.
          case Ident(n) => b.append("${").append(n).append('}')
          case Select(This(_), n) => b.append("${").append(n).append('}')
          case other => b.append("${").append(emitExpr(other)).append('}')
        if partsIter.hasNext then b.append(escapeDartString(partsIter.next()))
      b.append('\'')
      b.toString

    /** Emit the body of a lifted anonymous function as a Dart arrow or block
     *  expression. DefDef's `rhs` is the lambda body.
     */
    private def emitClosure(dd: DefDef): String =
      val params = dd.paramss.flatMap(_.params).collect { case vd: ValDef => vd }
      val paramStr = params.map(p => p.name).mkString(", ")
      // `() => async { body }` unwraps to an async closure over the body;
      // otherwise a body containing `await` still marks the closure async.
      val unwrapped = dd.rhs.flatMap(unwrapAsync)
      // Normalize Inlined/Typed wrappers so block bodies match the
      // statement-emitting branches instead of degrading to arrow+IIFE
      // (which would strand awaits inside a non-async closure).
      def normalizeTerm(t: Term): Term = t match
        case Inlined(_, _, e) => normalizeTerm(e)
        case Typed(e, _)      => normalizeTerm(e)
        case other            => other
      val effectiveRhs = unwrapped.orElse(dd.rhs).map(normalizeTerm)
      val asyncMark =
        if unwrapped.isDefined || dd.rhs.exists(containsAwait) then " async" else ""
      effectiveRhs match
        case Some(body) =>
          body match
            // Unit-typed statement `if` as the whole body — a real `if`
            // statement, never a void-operand ternary.
            case ifTerm @ If(_, _, _) if isUnitTyped(ifTerm) =>
              s"($paramStr)$asyncMark { ${stmtInline(ifTerm)} }"
            // A statless Block wrapping a try/catch — statement-only in
            // Dart, so block form.
            case Block(Nil, tryTree: Try) =>
              s"($paramStr)$asyncMark { ${stmtInline(tryTree)} }"
            // A statless Block is just a wrapper — unwrap to the arrow form.
            case Block(Nil, expr: Term) =>
              s"($paramStr)$asyncMark => ${emitExpr(expr)}"
            // Temp-val desugar inside a closure body — inline the same way
            // we do for method bodies. Without this, closures that build
            // a widget with named/default args come out as `(ctx, i) {
            // final Foo x$1 = …; ListTile(x$1, …); }` with a dangling
            // statement and default-ref leaks.
            //
            // The guard uses `case _: ValDef` rather than `isInstanceOf`
            // because the quoted-reflect runtime classes for `DefDef` and
            // `ValDef` overlap at the JVM level — an `isInstanceOf` check
            // would wrongly admit blocks whose stats are inner closure
            // DefDefs, strip them, and emit the trailing `Literal(())` as
            // `null` (regression hit by `onTap = () => pushRoute(...)`).
            // Await-bearing bodies skip the inline path — statements keep
            // vals as real locals inside the async block.
            case Block(stats, expr: Term) if asyncMark.isEmpty && stats.nonEmpty && stats.forall { case _: ValDef => true; case _ => false } =>
              val inlined = inlineTempValBlock(stats.collect { case vd: ValDef => vd }, expr)
              s"($paramStr) => $inlined"
            case Block(stats, expr) =>
              // A closure DECLARED Unit never `return`s its trailing value
              // — Dart forbids returning values from a void block body.
              val closureReturnsUnit =
                dd.returnTpt.tpe.typeSymbol.fullName == "scala.Unit"
              val sb = new StringBuilder(s"($paramStr)$asyncMark { ")
              stats.foreach { s =>
                sb.append(stmtInline(s))
                sb.append(' ')
              }
              expr match
                case Literal(c) if c.value == () => ()
                // Unit-typed trailing terms route through stmtInline so
                // statement `if`s stay statements.
                case term: Term if isUnitTyped(term) => sb.append(stmtInline(term)).append(' ')
                case term: Term if closureReturnsUnit => sb.append(emitExpr(term)).append("; ")
                case term: Term => sb.append("return ").append(emitExpr(term)).append("; ")
                case _ => ()
              sb.append("}")
              sb.toString
            case Assign(lhs, rhs) =>
              s"($paramStr)$asyncMark { ${emitExpr(lhs)} = ${emitExpr(rhs)}; }"
            // A try/catch body is statement-only in Dart — block form.
            case tryTree: Try =>
              s"($paramStr)$asyncMark { ${stmtInline(tryTree)} }"
            case term: Term =>
              s"($paramStr)$asyncMark => ${emitExpr(term)}"
        case None => s"($paramStr) => null"

    /** Inline a `Block(ValDef*, trailingExpr)` desugar — typical output of
     *  Scala's constructor-call lowering for default/reordered named args —
     *  by substituting each val's emitted RHS back into the trailing
     *  expression via text replacement. ValDefs whose RHS is a
     *  `…$default$N` synthesiser get stripped from the resulting call.
     */
    private def inlineTempValBlock(stats: List[ValDef], expr: Term): String =
      val marker = "__SART_DEFAULT_ARG__"
      // Not `\b`: compiler temps like `$1$` start/end with `$`, which
      // isn't a regex word character, so `\b` never matches around it.
      def substitute(in: String, name: String, value: String): String =
        in.replaceAll(
          s"(?<![A-Za-z0-9_$$])${java.util.regex.Pattern.quote(name)}(?![A-Za-z0-9_$$])",
          java.util.regex.Matcher.quoteReplacement(value)
        )
      def occurrences(in: String, name: String): Int =
        s"(?<![A-Za-z0-9_$$])${java.util.regex.Pattern.quote(name)}(?![A-Za-z0-9_$$])".r
          .findAllMatchIn(in).size

      val (defaultVals, realVals) = stats.partition(_.rhs.exists(isDefaultArg))

      var out = emitExpr(expr)
      for vd <- defaultVals do out = substitute(out, vd.name, marker)

      // Strip arguments whose value is the default-arg marker. Handle the
      // various surrounding-comma/paren shapes that can appear.
      val id = "[a-zA-Z_$][a-zA-Z_0-9$]*"
      out = out
        .replaceAll(s"$id: $marker, ",        "")
        .replaceAll(s", $id: $marker",        "")
        .replaceAll(s"$marker, ",             "")
        .replaceAll(s", $marker",             "")
        .replaceAll(s"\\($marker\\)",         "()")
        .replaceAll(s"$id: $marker",          "")
        .replaceAll(marker,                   "null")  // any survivor → `null`

      // Inline the remaining vals only when each is referenced at most
      // once — substituting a multi-use val would duplicate its
      // computation (e.g. re-running a jsonDecode or an http call).
      // Process in reverse declaration order so a later val's inlined
      // RHS still gets earlier vals substituted into it.
      // A substituted RHS that isn't a single atom (identifier, literal,
      // one balanced call/list/paren group) gets parenthesised — dropping
      // a bare ternary or binary chain into `<name>.member` would rebind
      // by precedence (`a ? b : c.member`).
      def atomicRendered(s: String): Boolean =
        // Scanner for a postfix chain: Prim (('.'|'?.') ident | (…) | […] |
        // <…> | '…' | '!')* — anything that binds tighter than every infix
        // operator. Closures ((params) => e / (params) { … }) also count:
        // they only ever appear in argument position.
        var i = 0
        val n = s.length
        def scanGroup(open: Char, close: Char): Boolean =
          var depth = 0
          var inStr = false
          while i < n do
            val c = s(i)
            if inStr then
              if c == '\\' then i += 1
              else if c == '\'' then inStr = false
            else if c == '\'' then inStr = true
            else if c == open then depth += 1
            else if c == close then
              depth -= 1
              if depth == 0 then
                i += 1
                return true
            i += 1
          false
        def scanString(): Boolean =
          i += 1
          while i < n do
            val c = s(i)
            if c == '\\' then i += 1
            else if c == '\'' then
              i += 1
              return true
            i += 1
          false
        def scanIdent(): Boolean =
          val start = i
          while i < n && (s(i).isLetterOrDigit || s(i) == '_' || s(i) == '$') do i += 1
          i > start
        // Prim
        val primOk = s.nonEmpty && (s(0) match
          case '('            => scanGroup('(', ')')
          case '['            => scanGroup('[', ']')
          case '<'            => scanGroup('<', '>') && i < n && s(i) == '[' && scanGroup('[', ']')
          case '\''           => scanString()
          case c if c.isLetterOrDigit || c == '_' || c == '$' => scanIdent()
          case _              => false)
        if !primOk then false
        else if i >= n then true
        // Closure body following a parameter group.
        else if s.startsWith(" => ", i) || s.startsWith(" {", i) || s.startsWith(" async", i) then true
        else
          // Postfix chain
          var ok = true
          while ok && i < n do
            if s(i) == '.' then
              i += 1
              ok = scanIdent()
            else if s.startsWith("?.", i) then
              i += 2
              ok = scanIdent()
            else if s(i) == '!' then i += 1
            else if s(i) == '(' then ok = scanGroup('(', ')')
            else if s(i) == '[' then ok = scanGroup('[', ']')
            else if s(i) == '<' then ok = scanGroup('<', '>')
            else if s(i) == '\'' then ok = scanString()
            else ok = false
          ok && i >= n

      val preSubstituted = out
      var dup = false
      for vd <- realVals.reverse if !dup do
        if occurrences(out, vd.name) > 1 then dup = true
        else
          val rendered = vd.rhs.map(emitExpr).getOrElse("")
          val wrapped  = if atomicRendered(rendered) then rendered else s"($rendered)"
          out = substitute(out, vd.name, wrapped)

      if !dup then out
      else
        // Fall back to an IIFE that declares the vals and returns the
        // (marker-stripped, un-inlined) expression. Awaits inside make it
        // async + awaited.
        val hasAwait = realVals.exists(containsAwait) || containsAwait(expr)
        val asyncMark = if hasAwait then " async" else ""
        val sb = new StringBuilder(s"(()$asyncMark { ")
        realVals.foreach { vd =>
          sb.append(stmtInline(vd))
          sb.append(' ')
        }
        sb.append("return ").append(preSubstituted).append("; })()")
        if hasAwait then s"(await ${sb.toString})" else sb.toString

    private def isUnitLiteral(t: Tree): Boolean = t match
      case Literal(c) => c.value == ()
      case Block(Nil, inner) => isUnitLiteral(inner)
      case _ => false

    private def stmtInline(t: Tree): String = t match
      case vd: ValDef =>
        val isNullInit = vd.rhs.exists {
          case Literal(c) => c.value == null
          case _          => false
        }
        val init = vd.rhs.map(r => s" = ${emitExpr(r)}").getOrElse("")
        if !vd.symbol.flags.is(Flags.Mutable) && vd.rhs.nonEmpty && !isNullInit then
          // Type-inferred, like emitStmt — keeps nullability honest so
          // null-check promotion works on the local.
          s"final ${vd.name}$init;"
        else
          val prefix = if vd.symbol.flags.is(Flags.Mutable) then "" else "final "
          s"$prefix${emitTypeRef(vd.tpt.tpe)} ${vd.name}$init;"
      case Assign(lhs, rhs) => s"${emitExpr(lhs)} = ${emitExpr(rhs)};"
      // Statement-position `if` without a meaningful else — a real Dart
      // `if` statement, NOT a ternary (`cond ? voidCall() : null` is a
      // use_of_void_result error).
      case If(cond, thenp, elsep) if isUnitLiteral(elsep) =>
        s"if (${emitExpr(cond)}) { ${stmtInline(thenp)} }"
      case If(cond, thenp, elsep) =>
        s"if (${emitExpr(cond)}) { ${stmtInline(thenp)} } else { ${stmtInline(elsep)} }"
      // A lambda-shaped block is a single expression — don't tear it apart.
      case b @ Block(List(_: DefDef), _: Closure) =>
        s"${emitExpr(b)};"
      // Statement-position block (e.g. a multi-statement `if` branch) —
      // splice the statements instead of wrapping them in an IIFE, so
      // statement-only constructs (`while`, statement `if`) stay legal.
      case Block(stats, expr) =>
        val sb = new StringBuilder
        stats.foreach { s => sb.append(stmtInline(s)).append(' ') }
        expr match
          case Literal(c) if c.value == () => ()
          case term: Term                  => sb.append(stmtInline(term))
          case _                           => ()
        sb.toString.trim
      case While(cond, body) =>
        s"while (${emitExpr(cond)}) { ${stmtInline(body)} }"
      case t: Try =>
        stmtInlineTry(t)
      // Unit-typed `match` inline — a Dart switch *statement* (see the
      // block-form twin in `emitStmt`).
      case m @ Match(scrutinee, cases) if isUnitTyped(m) =>
        val arms = cases.map { c =>
          val usageScope: Tree = c.guard match
            case Some(g) => Block(List(g), c.rhs)
            case None    => c.rhs
          val pat   = emitPattern(c.pattern, usageScope)
          val guard = c.guard.map(g => s" when ${emitExpr(g)}").getOrElse("")
          val body  = if isUnitLiteral(c.rhs) then "break;" else stmtInline(c.rhs)
          s"case $pat$guard: $body"
        }.mkString(" ")
        s"switch (${emitExpr(scrutinee)}) { $arms }"
      case term: Term       => s"${emitExpr(term)};"
      case _                => s"/* TODO stmt-inline */"

    /** Single-line `try { … } on E catch (e) { … } finally { … }` — the
     *  inline twin of `emitTryStatement`, for closure/branch bodies that
     *  render on one line.
     */
    private def stmtInlineTry(t: Try): String =
      val sb = new StringBuilder("try { ")
      sb.append(stmtInline(t.body)).append(" }")
      for c <- t.cases do
        val header = c.pattern match
          case Typed(Ident("_"), tpt) =>
            s" on ${emitTypeRef(tpt.tpe)} {"
          case Bind(name, Typed(Ident("_"), tpt)) =>
            val tn = emitTypeRef(tpt.tpe)
            if bodyUsesIdent(c.rhs, name) then s" on $tn catch ($name) {" else s" on $tn {"
          case Bind(name, Ident("_")) =>
            if bodyUsesIdent(c.rhs, name) then s" catch ($name) {" else s" catch (_) {"
          case Ident("_") =>
            s" catch (_) {"
          case _ =>
            s" catch (_) { /* TODO complex catch pattern */"
        sb.append(header).append(' ').append(stmtInline(c.rhs)).append(" }")
      t.finalizer.foreach(f => sb.append(" finally { ").append(stmtInline(f)).append(" }"))
      sb.toString

    // ── Type references ──────────────────────────────────────────────────

    private def emitTypeRef(tpe: TypeRepr): String =
      val sym = tpe.typeSymbol
      recordAnnotations(sym)

      // Hand-ported stdlib types with custom Dart representations — these
      // need to bypass the standard `base<T, U>` template because they
      // format differently (e.g. `Option[T]` → `T?`, not `Option<T>`).
      sym.fullName match
        // The facade marker base class has no Dart-side existence — in
        // type position it's just "any Dart object".
        case "sart.dart.DartObject" =>
          return "Object"
        // The dynamic bridge: Sart's face of Dart `dynamic`.
        case "sart.dart.Dyn" =>
          return "dynamic"
        case "sart.stdlib.Option" | "scala.Option" =>
          // Both the hand-ported `sart.stdlib.Option` and Scala's built-in
          // `scala.Option` map to Dart's `T?` nullable. Flag the shim AND
          // its import so `.map` / `.flatMap` / `.fold` resolve in Dart.
          shimsNeeded += optionShim
          imports     += optionShim.fileName
          return tpe match
            case AppliedType(_, List(arg: TypeRepr)) =>
              val inner = emitTypeRef(arg)
              // `dynamic?` is redundant (dynamic already admits null) and
              // trips Dart's unnecessary_question_mark lint.
              if inner == "dynamic" || inner.endsWith("?") then inner else s"$inner?"
            case _                                   => "Object?"
        // scala.Function0..FunctionN → Dart `R Function(T1, …, Tn)`.
        case fqn if fqn.matches("scala\\.Function\\d+") =>
          return tpe match
            case AppliedType(_, args) if args.nonEmpty =>
              val Ts = args.init.map { case t: TypeRepr => emitTypeRef(t) }.mkString(", ")
              val R  = emitTypeRef(args.last.asInstanceOf[TypeRepr])
              s"$R Function($Ts)"
            case _ => "Function"
        // scala.Tuple2..Tuple22 → Dart record types `(T1, T2, …)`.
        // Field access (`_1`, `_2`, …) is rewritten via the stdlib table
        // to Dart record positional getters (`$1`, `$2`, …).
        case fqn if fqn.matches("scala\\.Tuple\\d+") =>
          return tpe match
            case AppliedType(_, args) if args.nonEmpty =>
              args.map { case t: TypeRepr => emitTypeRef(t) }.mkString("(", ", ", ")")
            case _ => "Object"
        case _ =>

      val base = sym.fullName match
        case "scala.Int"     => "int"
        case "scala.Long"    => "int"
        case "scala.Double"  => "double"
        case "scala.Float"   => "double"
        case "scala.Boolean" => "bool"
        case "scala.Unit"    => "void"
        // `dynamic`, not `Object`: Scala Any is the interop escape hatch,
        // and Dart facade generics/JSON maps materialise as <dynamic>.
        case "scala.Any" => "dynamic"
        case "scala.AnyRef" | "java.lang.Object" => "Object"
        case "scala.AnyVal"  => "Object"
        case "scala.Nothing" => "Never"
        case "java.lang.String" | "scala.Predef.String" => "String"
        // Throwables have no direct Dart analog; Dart uses `Object` as
        // the throwable super type for `catch (e)` and `throw e`. Match
        // simple name too because some Scala versions expose `Throwable`
        // without the `java.lang.` prefix we'd normally filter on.
        case fq if fq == "java.lang.Throwable" || fq == "scala.Throwable" ||
                   fq == "java.lang.Exception" || fq == "java.lang.RuntimeException" ||
                   sym.name == "Throwable" || sym.name == "Exception" => "Object"
        case _ => dartName(sym)

      // Render type arguments for `State[MyHomePage]` etc.
      tpe match
        case AppliedType(_, args) if args.nonEmpty =>
          val argStr = args.map {
            case t: TypeRepr => emitTypeRef(t)
          }.mkString("<", ", ", ">")
          base + argStr
        case _ =>
          base
